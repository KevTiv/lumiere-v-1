import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
export const browserOperationIdsPath = resolve(
  frontendRoot,
  "packages/stdb/src/generated/browser-operation-ids.ts",
)

/** Emit browser transport metadata from the installed, pinned session contracts. */
export function emitBrowserOperationIds(names, descriptors) {
  if (!Array.isArray(names) || descriptors === null || typeof descriptors !== "object") {
    throw new Error("session operation names and descriptors are required")
  }
  const sortedNames = [...names].sort()
  if (new Set(sortedNames).size !== sortedNames.length) {
    throw new Error("session operation names must be unique")
  }
  if (
    Object.keys(descriptors).length !== sortedNames.length ||
    sortedNames.some((name) => !Object.hasOwn(descriptors, name))
  ) {
    throw new Error("session operation names must match descriptor keys")
  }

  const ids = new Set()
  const entries = sortedNames.map((name) => {
    const descriptor = descriptors[name]
    if (
      typeof name !== "string" ||
      !/^[a-z][a-z0-9_]*$/.test(name) ||
      descriptor?.name !== name ||
      descriptor.exposure !== "session" ||
      typeof descriptor.contractOperationId !== "string" ||
      !/^erp\.[a-z0-9_]+$/.test(descriptor.contractOperationId)
    ) {
      throw new Error(`invalid session operation descriptor: ${String(name)}`)
    }
    if (ids.has(descriptor.contractOperationId)) {
      throw new Error(`duplicate contract operation ID: ${descriptor.contractOperationId}`)
    }
    ids.add(descriptor.contractOperationId)
    return `  ${JSON.stringify(name)}: ${JSON.stringify(descriptor.contractOperationId)},`
  })

  return [
    "// @generated by scripts/generate-browser-operation-ids.mjs from pinned @lumiere/contracts.",
    "// Do not edit. Regenerate with: node scripts/generate-browser-operation-ids.mjs",
    'import type { SessionOperationName } from "@lumiere/contracts/generated/operation-descriptors"',
    "",
    "export const SESSION_OPERATION_IDS = {",
    ...entries,
    "} as const satisfies Readonly<Record<SessionOperationName, string>>",
    "",
    "export const SESSION_OPERATION_NAMES = [",
    ...sortedNames.map((name) => `  ${JSON.stringify(name)},`),
    "] as const satisfies readonly SessionOperationName[]",
    "",
  ].join("\n")
}

/** Check drift without writing, or preserve the mtime of an unchanged output. */
export async function updateBrowserOperationIds(path, contents, { check = false } = {}) {
  let previous
  try {
    previous = await readFile(path, "utf8")
  } catch (error) {
    if (error.code !== "ENOENT") throw error
  }
  if (previous === contents) return false
  if (check) {
    throw new Error(
      "browser operation IDs are out of date; run node scripts/generate-browser-operation-ids.mjs from frontend/",
    )
  }
  await writeFile(path, contents)
  return true
}

async function main() {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("usage: node scripts/generate-browser-operation-ids.mjs [--check]")
  }
  // Resolve through the actual consumer instead of requiring a root dependency
  // or looking at an uninstalled, potentially different contracts checkout.
  const require = createRequire(resolve(frontendRoot, "packages/stdb/package.json"))
  const descriptorPath = require.resolve("@lumiere/contracts/generated/operation-descriptors")
  const { SESSION_OPERATION_NAMES, SESSION_OPERATION_DESCRIPTORS } = await import(
    pathToFileURL(descriptorPath).href
  )
  const contents = emitBrowserOperationIds(SESSION_OPERATION_NAMES, SESSION_OPERATION_DESCRIPTORS)
  const changed = await updateBrowserOperationIds(browserOperationIdsPath, contents, {
    check: args[0] === "--check",
  })
  console.log(
    `browser operation IDs ${changed ? "generated" : "verified"}: ${SESSION_OPERATION_NAMES.length} operations, ${Buffer.byteLength(contents)} source bytes`,
  )
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
}
