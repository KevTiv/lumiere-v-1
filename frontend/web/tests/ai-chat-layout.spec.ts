import { expect, test } from "@playwright/test"

// Geometry and interactions use the real shell and panel; replies are simulated.
for (const width of [320, 390, 768, 1024, 1440]) {
  test(`keeps ERP and chat usable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/chat-workspace")
    const reference = page.getByRole("textbox", { name: "Invoice reference" })
    await reference.fill("Unsent invoice reference")
    await page.getByRole("button", { name: "Ask Lumière", exact: true }).last().click()
    const panel = page.getByTestId("erp-ai-chat-panel")
    const input = page.getByTestId("erp-ai-chat-input")
    await expect(input).toBeFocused()
    const bounds = (await panel.boundingBox())!
    expect(bounds.y).toBe(width >= 1024 ? 12 : 0)
    expect(bounds.height).toBe(width >= 1024 ? 876 : 900)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    if (width >= 1024) {
      await expect(page.getByTestId("sidebar-open-ai-chat")).toHaveAttribute("aria-pressed", "true")
      const erp = (await page.getByTestId("workspace-content").boundingBox())!
      expect(erp.x + erp.width).toBeLessThanOrEqual(bounds.x)
      await reference.fill("Edited alongside chat")
    } else {
      expect(bounds.x).toBe(0)
      expect(bounds.width).toBe(width)
    }
    await input.fill("Keep this question")
    await expect(panel.getByRole("group", { name: "ERP quick actions" })).toBeHidden()
    await expect(panel.locator("header")).toHaveCSS("border-bottom-width", "0px")
    await panel.getByRole("button", { name: "Skills", exact: true }).click()
    await panel.getByRole("button", { name: "Create a draft", exact: true }).click()
    await expect(input).toHaveValue("Keep this question")
    await expect(panel.getByRole("button", { name: "Create a draft", exact: true })).toHaveAttribute("aria-pressed", "true")
    await expect(panel.getByTestId("erp-ai-chat-message-user")).toHaveCount(0)
    await panel.getByRole("button", { name: "Open full workspace" }).click()
    await expect(panel).toHaveAttribute("data-mode", "full")
    await expect(input).toHaveValue(/^Keep this question/)
    await panel.getByRole("button", { name: "Dock beside ERP" }).click()
    await input.fill("Check overflow wrapping of long record references.")
    await panel.getByRole("button", { name: "Send message" }).click()
    const reply = panel.getByTestId("erp-ai-chat-message-assistant")
    await expect(reply).toContainText("Review the customer")
    await expect(panel.getByRole("group", { name: "ERP quick actions" })).toBeVisible()
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const answer = (await reply.boundingBox())!
    const composer = (await input.locator("..").boundingBox())!
    expect(Math.abs(answer.x - composer.x)).toBeLessThanOrEqual(1)
    expect(Math.abs(answer.width - composer.width)).toBeLessThanOrEqual(1)
    await panel.getByRole("button", { name: "Close", exact: true }).click()
    await expect(reference).toHaveValue(width >= 1024 ? "Edited alongside chat" : "Unsent invoice reference")
  })
}

for (const width of [390, 1440]) {
  test(`scrolls skills into view and keeps multiple selections at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/chat-workspace")
    await page.getByRole("button", { name: "Ask Lumière", exact: true }).last().click()
    const panel = page.getByTestId("erp-ai-chat-panel")
    const input = panel.getByTestId("erp-ai-chat-input")
    await panel.getByRole("button", { name: "Skills", exact: true }).click()
    const list = panel.getByRole("region", { name: "Skills" })
    expect(await list.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
    await list.hover()
    await page.mouse.wheel(0, 200)
    await expect.poll(() => list.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await input.fill("Review my invoices /bank")
    const reconcile = panel.getByRole("button", { name: "Reconcile accounts", exact: true })
    await expect(reconcile).toHaveAttribute("data-active", "true")
    const unselected = await reconcile.evaluate(element => ({ border: getComputedStyle(element).borderColor, background: getComputedStyle(element).backgroundColor }))
    await input.press("Enter")
    await expect(input).toHaveValue("Review my invoices ")
    await expect(reconcile).toHaveAttribute("aria-pressed", "true")
    await expect(reconcile).not.toHaveCSS("border-color", unselected.border)
    await expect(reconcile).not.toHaveCSS("background-color", unselected.background)
    await input.press("End")
    await input.pressSequentially("/report")
    await expect(panel.getByRole("button", { name: "Generate report", exact: true }).last()).toHaveAttribute("data-active", "true")
    await input.press("Tab")
    const selected = panel.getByRole("group", { name: "Selected skills" })
    await expect(selected.getByRole("button")).toHaveCount(2)
    await expect(panel.getByTestId("erp-ai-chat-message-user")).toHaveCount(0)
    await input.fill("Review my invoices /nothing-matches")
    await expect(panel.getByText("No matching skills. Try another name.")).toBeVisible()
    await input.press("Enter")
    await expect(panel.getByTestId("erp-ai-chat-message-user")).toHaveCount(0)
    await input.press("Escape")
    await input.fill("Review my invoices")
    await selected.getByRole("button", { name: "Remove Reconcile accounts" }).click()
    await expect(selected.getByRole("button")).toHaveCount(1)
    await expect(input).toHaveValue("Review my invoices")
    await list.getByRole("button", { name: "Generate report", exact: true }).focus()
    await page.keyboard.press("ArrowRight")
    await expect(list.getByRole("button", { name: "Explain this page", exact: true })).toBeFocused()
    await page.keyboard.press("ArrowDown")
    await expect(list.getByRole("button", { name: "Reconcile accounts", exact: true })).toBeFocused()
    expect(await list.evaluate(element => element.scrollTop > 0)).toBe(true)
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  })
}
