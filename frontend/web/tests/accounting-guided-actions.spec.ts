import { test, expect } from "@playwright/test"

for (const viewport of [{ width: 390, height: 600 }, { width: 1440, height: 900 }]) {
  test.describe(`guided accounting actions ${viewport.width}px`, () => {
    test.use({ viewport })
    test.beforeEach(async ({ page }) => {
      await page.goto("/guided-workflows")
      await expect(page.getByTestId("guided-fixture-disclosure")).toHaveAttribute("data-hydrated", "true")
    })
    test("invoice and bill flows explain the action, retain a rejected selection, and link the confirmed result", async ({ page }, testInfo) => {
      for (const isBill of [false, true]) {
        if (isBill) await page.getByRole("button", { name: "Switch document kind" }).click()
        const guide = page.getByTestId("invoice-workflow-guide")
        await expect(guide).toContainText("Saving a draft does not post it to the ledger")
        await page.getByRole("button", { name: "Review line items" }).click()
        await expect(page.getByText("Review synthetic line:", { exact: false })).toBeVisible()
        await page.getByRole("button", { name: isBill ? "Post bill" : "Post invoice", exact: true }).click()
        await expect(guide).toContainText(isBill ? "does not send money to your vendor" : "does not charge your customer")
        await page.screenshot({ path: testInfo.outputPath(`next-step-${isBill ? "bill" : "invoice"}.png`) })
        await page.getByRole("button", { name: "Toggle rejected payment" }).click()
        await page.getByRole("button", { name: "Apply existing payment", exact: true }).click()
        const dialog = page.getByTestId("apply-posted-payment-dialog")
        await expect(dialog.getByRole("button", { name: "Apply payment", exact: true })).toBeDisabled()
        await dialog.getByRole("combobox", { name: "Posted payment" }).click()
        await page.getByRole("option", { name: "PAY/001 · EUR 125.00" }).click()
        await dialog.getByRole("button", { name: "Apply payment", exact: true }).click()
        await expect(dialog.getByRole("alert")).toContainText("Synthetic payment rejected; selection retained")
        await expect(dialog.getByRole("combobox")).toContainText("PAY/001")
        const bounds = await dialog.boundingBox()
        expect(bounds!.y).toBeGreaterThanOrEqual(0)
        expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height)
        await page.screenshot({ path: testInfo.outputPath(`payment-rejection-${isBill ? "bill" : "invoice"}.png`) })
        await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
        await page.getByRole("button", { name: "Toggle rejected payment" }).click()
        await page.getByRole("button", { name: "Apply existing payment", exact: true }).click()
        await page.getByRole("combobox", { name: "Posted payment" }).click()
        await page.getByRole("option", { name: "PAY/001 · EUR 125.00" }).click()
        await page.getByRole("button", { name: "Apply payment", exact: true }).click()
        await expect(dialog).toHaveCount(0)
        await expect(guide).toContainText("Payment complete")
        await expect(page.getByRole("link", { name: "View linked payments" })).toHaveAttribute("href", "#linked-payments")
        const sizes = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth }))
        expect(sizes.document).toBeLessThanOrEqual(sizes.width)
      }
      await expect(page.getByTestId("guided-dispatches")).toContainText("Payment applications: 4")
    })
    test("permission and source failures explain why the next action is unavailable", async ({ page }) => {
      await page.getByRole("button", { name: "Toggle permission" }).click()
      await expect(page.getByTestId("invoice-next-step-action")).toBeDisabled()
      await expect(page.getByTestId("invoice-next-step-blocked")).toBeVisible()
      await page.getByRole("button", { name: "Toggle permission" }).click()
      await page.getByRole("button", { name: "Post invoice", exact: true }).click()
      await page.getByRole("button", { name: "Cycle payment source" }).click()
      await page.getByRole("button", { name: "Apply existing payment", exact: true }).click()
      const dialog = page.getByTestId("apply-posted-payment-dialog")
      await expect(dialog).toContainText("Loading posted payments")
      await expect(dialog).not.toContainText("No posted payments available")
      await expect(dialog.getByRole("button", { name: "Apply payment", exact: true })).toBeDisabled()
    })
  })
}

test("accounting desk puts task queues before charts and preserves exact queue drill-through", async ({ page }, testInfo) => {
  await page.goto("/")
  await expect(page.getByTestId("fixture-disclosure")).toHaveAttribute("data-hydrated", "true")
  const queue = page.getByRole("region", { name: "Needs attention", exact: true })
  await expect(queue).toBeVisible()
  const positions = await page.evaluate(() => ({ queues: document.getElementById("accountant-attention-title")!.getBoundingClientRect().top, insights: document.getElementById("financial-overview-title")!.getBoundingClientRect().top }))
  expect(positions.queues).toBeLessThan(positions.insights)
  await page.getByTestId("accountant-queue-draft-invoices").click()
  await expect(page.getByRole("link", { name: "Open filtered list" })).toHaveAttribute("href", "/accounting?tab=invoices&filter=status%3ADraft")
  await page.getByTestId("accountant-queue-bills-due").click()
  await expect(page.getByRole("region", { name: "Bills due soon", exact: true })).toContainText("next seven days")
  await page.screenshot({ path: testInfo.outputPath("accounting-desk.png"), fullPage: true })
})
