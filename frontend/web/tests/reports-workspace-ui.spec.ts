import { expect, test } from "@playwright/test"

for (const viewport of [{ width: 390, height: 844 }, { width: 1440, height: 900 }]) {
  test.describe(`Reports journey at ${viewport.width}px`, () => {
    test.use({ viewport })
    test.setTimeout(120_000)
    test("generate, retain rejected entries, reopen exact output, reload and return", async ({ page }, info) => {
      const requests: string[] = []
      const errors: string[] = []
      page.on("request", (request) => { if (new URL(request.url()).pathname.startsWith("/api/")) requests.push(request.url()) })
      page.on("pageerror", (error) => errors.push(error.message))
      await page.goto("/reports-workspace?before=1", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await page.screenshot({ path: info.outputPath(`before-${viewport.width}.png`), fullPage: true })
      await page.goto("/reports-workspace", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await expect(page.getByTestId("report-start")).toBeVisible()
      await page.screenshot({ path: info.outputPath(`after-${viewport.width}.png`), fullPage: true })
      await page.getByRole("button", { name: "Reject synthetic save", exact: true }).click()
      await page.getByRole("button", { name: "Run Profit & loss", exact: true }).click()
      const form = page.getByTestId("form-modal-new-financial-report")
      await expect(form.getByRole("combobox", { name: /Report type/ })).toContainText("Profit & loss")
      await form.getByRole("textbox", { name: /Report Name/ }).fill("Synthetic October P&L")
      await form.getByRole("textbox", { name: /From Date/ }).fill("2026-10-01")
      await form.getByRole("textbox", { name: /To Date/ }).fill("2026-10-31")
      await form.getByRole("button", { name: "Generate report", exact: true }).click()
      await expect(form.getByRole("alert")).toContainText("Synthetic generation rejected")
      await expect(form.getByRole("textbox", { name: /Report Name/ })).toHaveValue("Synthetic October P&L")
      await expect(form.getByRole("textbox", { name: /From Date/ })).toHaveValue(/Oct 1, 2026|2026-10-01/)
      await form.getByRole("button", { name: "Generate report", exact: true }).click()
      await expect(page).toHaveURL(/report=9007199254740995/)
      await expect(page.getByTestId("report-result")).toContainText("Synthetic October P&L")
      await expect(page.getByTestId("report-result")).toContainText("Posted entries only")
      await page.reload({ waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await expect(page.getByTestId("synthetic-report-output")).toContainText("Synthetic October P&L")
      await page.getByRole("button", { name: "Export CSV", exact: true }).click()
      await expect(page.getByRole("status").filter({ hasText: "Synthetic CSV requested" })).toBeVisible()
      await page.getByRole("button", { name: "Back to saved reports", exact: true }).click()
      await page.getByRole("button", { name: "October trial balance", exact: true }).click()
      await expect(page).toHaveURL(/report=9007199254740993/)
      await expect(page.getByTestId("report-result")).toContainText("Previous period")
      await page.screenshot({ path: info.outputPath(`result-${viewport.width}.png`), fullPage: true })
      expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
      expect(requests).toEqual([])
      expect(errors).toEqual([])
    })

    test("missing, loading and denied reports never show a substitute output", async ({ page }) => {
      await page.goto("/reports-workspace?tab=reports&report=999", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await expect(page.getByTestId("report-result")).toContainText("unavailable in the selected company or period")
      await expect(page.getByTestId("synthetic-report-output")).toHaveCount(0)
      await page.goto("/reports-workspace?tab=reports&report=9007199254740993", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await page.getByRole("button", { name: "Fail synthetic source", exact: true }).click()
      await expect(page.getByTestId("report-result").getByRole("alert")).toContainText("Records could not be loaded")
      await expect(page.getByTestId("synthetic-report-output")).toHaveCount(0)
      await page.getByRole("button", { name: "Retry", exact: true }).click()
      await expect(page.getByTestId("synthetic-report-output")).toBeVisible()
      await page.getByRole("button", { name: "Load synthetic source", exact: true }).click()
      await expect(page.getByTestId("synthetic-report-output")).toHaveCount(0)
      await page.getByRole("button", { name: "Deny synthetic source", exact: true }).click()
      await expect(page.getByTestId("report-result")).toContainText("do not have access")
      await expect(page.getByRole("button", { name: "Export CSV", exact: true })).toHaveCount(0)
    })

    test("period-launched catalog offers only its locked report type and readers cannot generate", async ({ page }) => {
      await page.goto("/reports-workspace?locked=1", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await expect(page.getByRole("button", { name: "Run Trial balance", exact: true })).toBeVisible()
      await expect(page.getByRole("heading", { name: "Profit & loss", exact: true })).toHaveCount(0)
      await page.goto("/reports-workspace?readOnly=1", { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("reports-fixture-disclosure")).toHaveAttribute("data-hydrated", "true", { timeout: 60_000 })
      await expect(page.getByRole("button", { name: "Generate report", exact: true })).toHaveCount(0)
      await expect(page.getByTestId("report-start")).toContainText("review saved reports")
    })
  })
}
