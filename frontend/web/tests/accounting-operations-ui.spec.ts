    test("actual payment allocation retains its pending request and exact retry after a lost synthetic response", async ({ page }, testInfo) => {
      const requests: unknown[] = []
      let pendingRoute: Route | undefined
      await page.route(`**${stdbBffCallUrl("allocate_payment_transaction")}`, async (route) => {
        requests.push(route.request().postDataJSON())
        if (requests.length === 1) pendingRoute = route
        else await route.fulfill({ status: 200, contentType: "application/json", body: "{}" })
      })
      await page.getByRole("button", { name: "Payment allocation", exact: true }).click()
      await expect(page.getByTestId("payment-allocation-balance-301")).toContainText("40.00 allocated · 60.00 remaining")
      await page.getByRole("button", { name: "Allocate", exact: true }).click()
      const dialog = page.getByRole("dialog", { name: "Allocate payment", exact: true })
      await dialog.getByRole("combobox", { name: /Invoice or bill line/ }).click()
      await page.getByRole("option", { name: /Customer invoice INV\/BANK\/91/ }).click()
      await dialog.getByRole("textbox", { name: /Allocation amount/ }).fill("20")
      await dialog.getByRole("button", { name: "Allocate payment", exact: true }).click()
      await expect.poll(() => requests.length).toBe(1)
      await expect(page.getByTestId("operations-state")).toContainText("payment lock true")
      await control(page, "collections")
      // The open modal hides siblings from accessible-name queries; verify its
      // original parent remains rendered and the reviewed dialog remains intact.
      await expect(page.locator('section[aria-label="Retained payment allocation"]')).toBeVisible()
      await expect(dialog).toBeVisible()
      await expect(dialog.getByRole("textbox", { name: /Allocation amount/ })).toHaveValue("20.00")
      await pendingRoute!.fulfill({ status: 504, contentType: "application/json", body: JSON.stringify({ error: "Synthetic allocation response lost" }) })
      await expect(dialog).toContainText("Synthetic allocation response lost")
      await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
      await page.getByRole("alertdialog", { name: "Discard changes?", exact: true }).getByRole("button", { name: "Discard", exact: true }).click()
      await expect(dialog).toHaveCount(0)
      const retained = page.getByRole("region", { name: "Retained payment allocation" })
      await expect(retained).toContainText("allocation response is unresolved")
      await expect(page.getByTestId("operations-state")).toContainText("payment lock true")
      await control(page, "22")
      await expect(retained.getByRole("button", { name: "Retry original allocation", exact: true })).toBeDisabled()
      expect(requests).toHaveLength(1)
      await control(page, "11")
      await expect(retained.getByRole("button", { name: "Retry original allocation", exact: true })).toBeEnabled()
      await noOverflow(page)
      await page.screenshot({ path: testInfo.outputPath(`payment-recovery-${width}.png`), fullPage: true })
      await retained.getByRole("button", { name: "Retry original allocation", exact: true }).click()
      await expect.poll(() => requests.length).toBe(2)
      expect(requests[1]).toEqual(requests[0])
      await expect(page.getByRole("region", { name: "Retained payment allocation" })).toHaveCount(0)
    })

