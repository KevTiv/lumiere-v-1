    test("email review validates literal queue content and keeps compact-height actions reachable", async ({ page }) => {
      await openEmail(page)
      const dialog = page.getByTestId("invoice-email-review")
      const template = dialog.getByTestId("invoice-email-template")
      await expect(template.locator("option", { hasText: "FOREIGN COMPANY" })).toHaveCount(0)
      await dialog.getByTestId("invoice-email-recipient").fill("not-an-email")
      await expect(dialog.getByTestId("invoice-email-queue")).toBeDisabled()
      await template.selectOption("103")
      await expect(dialog.getByRole("alert")).toContainText(/attachment/i)
      await expect(dialog.getByTestId("invoice-email-queue")).toBeDisabled()
      await template.selectOption("104")
      await expect(dialog.getByRole("alert")).toContainText(/placeholder/i)
      await template.selectOption("101")
      await expect(dialog.getByTestId("invoice-email-body")).toContainText("<strong>Synthetic literal message</strong>")
      await expect(dialog.getByTestId("invoice-email-body").locator("strong")).toHaveCount(0)
      await approveEmail(page)
      await dialog.getByRole("button", { name: "Review PDF", exact: true }).click()
      await touchTargets(page, width, [dialog.getByTestId("invoice-email-recipient"), template, dialog.getByTestId("invoice-email-queue"), dialog.locator('label[for="invoice-email-reviewed"]')])
      if (width < 768) {
        await page.setViewportSize({ width, height: 480 })
        await dialog.getByTestId("invoice-email-queue").scrollIntoViewIfNeeded()
        await expect(dialog.getByTestId("invoice-email-queue")).toBeInViewport()
        await expect(dialog.getByRole("button", { name: "Close review", exact: true })).toBeInViewport()
      }
      await noOverflow(page)
      await dialog.getByTestId("invoice-email-queue").click()
      await expect(dialog.getByTestId("invoice-email-result")).toContainText("Email queue confirmed")
      await expect(dialog.getByTestId("invoice-email-result")).toContainText("Sending and delivery are not confirmed")
      await expect(dialog.getByTestId("invoice-email-queue")).toHaveCount(0)
      await dialog.getByRole("button", { name: "Close review", exact: true }).click()
      await expect(page.getByTestId("workflow-fixture-state")).toContainText(`email dispatches 1; email checks 0; PDF review ${exactInvoice}`)
      await noOverflow(page)
    })

    test("email rejection retains edits and unknown recovery cannot retarget or replay across company changes", async ({ page }) => {
      await page.getByRole("button", { name: "Reject synthetic email action", exact: true }).click()
      await openEmail(page)
      const dialog = page.getByTestId("invoice-email-review")
      await approveEmail(page)
      await dialog.getByTestId("invoice-email-queue").click()
      await expect(dialog.getByRole("alert")).toContainText("Synthetic queue rejection")
      await expect(dialog.getByTestId("invoice-email-recipient")).toHaveValue("alpha@example.test")
      await dialog.getByRole("button", { name: "Close review", exact: true }).click()
      await page.getByRole("button", { name: "Lose synthetic email response", exact: true }).click()
      await page.getByRole("button", { name: "Review synthetic invoice email", exact: true }).click()
      await dialog.getByTestId("invoice-email-queue").click()
      await expect(dialog.getByTestId("invoice-email-result")).toContainText("Queue status unknown")
      await dialog.getByRole("button", { name: "Close review", exact: true }).click()
      await page.getByRole("button", { name: "Switch synthetic company", exact: true }).click()
      await page.getByRole("button", { name: "Review synthetic invoice email", exact: true }).click()
      await expect(dialog.getByRole("alert")).toContainText(`This review still belongs to INV/SYNTHETIC/${exactInvoice}`)
      await expect(dialog.getByTestId("invoice-email-check")).toBeDisabled()
      await expect(dialog.getByTestId("invoice-email-recipient")).toHaveCount(0)
      await dialog.getByRole("button", { name: "Close review", exact: true }).click()
      await page.getByRole("button", { name: "Switch synthetic company", exact: true }).click()
      await page.getByRole("button", { name: "Toggle synthetic action permission", exact: true }).click()
      await page.getByRole("button", { name: "Review synthetic invoice email", exact: true }).click()
      await expect(dialog.getByTestId("invoice-email-check")).toBeEnabled()
      await dialog.getByTestId("invoice-email-check").click()
      await expect(dialog).toContainText("Original queue review retained")
      await dialog.getByTestId("invoice-email-check").click()
      await expect(dialog).toContainText("Its queue record was confirmed. Sending and delivery are not confirmed.")
      await dialog.getByRole("button", { name: "Close review", exact: true }).click()
      await expect(page.getByTestId("workflow-fixture-state")).toContainText("email dispatches 2; email checks 2")
      await noOverflow(page)
    })

    test("legacy buyer identity is explicitly unavailable and V2 legal details stay captured after CRM changes", async ({ page }) => {
      await page.getByRole("tab", { name: "Buyer snapshots", exact: true }).click()
      const legacy = page.getByRole("region", { name: "Legacy buyer snapshot", exact: true })
      const captured = page.getByRole("region", { name: "Captured buyer snapshot", exact: true })
      await expect(legacy).toContainText("Customer billing details were not captured")
      await expect(legacy).not.toContainText("CAPTURED-BUYER-TAX")
      await expect(captured).toContainText("Captured Buyer Legal Identity Limited")
      await expect(captured).toContainText("10 Captured Legal Street")
      await expect(captured).toContainText("CAPTURED-BUYER-TAX")
      await expect(captured).toContainText("captured-buyer@example.test")
      const draft = page.getByRole("region", { name: "Draft captured buyer snapshot", exact: true })
      await expect(draft).toContainText("Captured Buyer Legal Identity Limited")
      await expect(draft).toContainText("Captured when this draft was created. Posting refreshes billing details from the linked customer.")
      await page.getByRole("button", { name: "Change synthetic live CRM contact", exact: true }).click()
      await expect(page.getByTestId("synthetic-live-contact")).toContainText("Changed CRM")
      await expect(captured).not.toContainText("Changed CRM")
      await expect(draft).not.toContainText("Changed CRM")
      await page.getByRole("button", { name: "Dark workspace", exact: true }).click()
      await expect(page.locator("html")).toHaveClass(/dark/)
      await expect(captured.getByTestId("invoice-document")).toHaveCSS("background-color", "rgb(255, 255, 255)")
      await noOverflow(page)
    })
