import { expect, test, type Page } from "@playwright/test"

import { gotoModule, signIn, smokeName } from "./helpers"
import {
  expectCanonicalPickingFocus,
  fetchPickingState,
  runPickingActionViaInventoryUi,
} from "./inventory-picking-fixtures"
import {
  addLaptopLine,
  confirmOrderViaUi,
  createDraftSaleOrder,
  fetchOrderPickings,
} from "./sales-order-fixtures"

// COV-24 — see docs/plan/erp-cov24-distributor-workspace-status.md.
const PERSONA_PASSWORD = process.env.E2E_FIRST_ORG_PERSONA_PASSWORD ?? "Password123$"

/** The canonical record links the workspace must produce (`buildModuleTabHref`). */
const orderHref = (id: number) => `/sales?tab=orders&filter=${encodeURIComponent(`id:${id}`)}`
const pickingHref = (id: number) => `/inventory?tab=transfers&filter=${encodeURIComponent(`id:${id}`)}`

async function openWorkspace(page: Page) {
  await gotoModule(page, "/distributor", "distributor")
  const enable = page.getByRole("button", { name: /^Enable (distributor )?pack$/i }).first()
  if (await enable.isVisible({ timeout: 5_000 }).catch(() => false)) {
    await enable.click()
  }
  await expect(page.getByTestId("distributor-o2c")).toBeVisible({ timeout: 30_000 })
}

test.describe("COV-24 distributor order-to-cash workspace", { tag: ["@p0", "@cov24", "@unauthenticated"] }, () => {
  test("a confirmed order shows its delivery exception and links to the canonical records", async ({ browser, page }) => {
    test.setTimeout(300_000)

    // Fixtures: one confirmed order (its delivery is generated by the canonical confirm) and
    // one draft order that must not appear. Both are created through the sales UI.
    await signIn(page, "test@email.com", PERSONA_PASSWORD)
    const orderId = await createDraftSaleOrder(page, smokeName("cov24-o2c"))
    await addLaptopLine(page, orderId, "1")
    await confirmOrderViaUi(page, orderId)
    const [delivery] = await fetchOrderPickings(page, orderId)
    expect(delivery, "confirming the order must generate its delivery").toBeTruthy()
    const draftOrderId = await createDraftSaleOrder(page, smokeName("cov24-draft"))

    // ── Delivery not done: the exception, the stage and exact links ───────
    await openWorkspace(page)
    const row = page.getByTestId(`distributor-o2c-row-${orderId}`)
    await expect(row).toBeVisible({ timeout: 30_000 })
    await expect(page.getByTestId(`distributor-o2c-stage-${orderId}`)).toHaveText("To deliver")
    await expect(page.getByTestId(`distributor-o2c-exception-${orderId}-delivery_incomplete`)).toBeVisible()
    await expect(page.getByTestId(`distributor-o2c-exception-${orderId}-no_delivery`)).toHaveCount(0)
    await expect(page.getByTestId(`distributor-o2c-order-${orderId}`)).toHaveAttribute("href", orderHref(orderId))
    await expect(page.getByTestId(`distributor-o2c-${orderId}-picking-${delivery!.id}`)).toHaveAttribute(
      "href",
      pickingHref(delivery!.id),
    )
    await expect(page.getByTestId(`distributor-o2c-row-${draftOrderId}`)).toHaveCount(0)

    // The picking link lands on exactly that transfer in Inventory.
    await page.getByTestId(`distributor-o2c-${orderId}-picking-${delivery!.id}`).click()
    await expectCanonicalPickingFocus(page, delivery!.id)

    // ── Deliver it through the canonical Inventory actions ────────────────
    const next = { draft: "confirm", confirmed: "assign", assigned: "validate" } as const
    for (let step = 0; step < 3; step += 1) {
      const state = await fetchPickingState(page, delivery!.id)
      if (state === "done") break
      const action = next[state as keyof typeof next]
      expect(action, `unexpected picking state ${state}`).toBeTruthy()
      await runPickingActionViaInventoryUi(page, delivery!.id, action)
    }
    await expect.poll(() => fetchPickingState(page, delivery!.id), { timeout: 30_000 }).toBe("done")

    // ── Delivered but not invoiced: the exception moves to the next stage ─
    await openWorkspace(page)
    await expect(page.getByTestId(`distributor-o2c-stage-${orderId}`)).toHaveText("To invoice", { timeout: 30_000 })
    await expect(page.getByTestId(`distributor-o2c-exception-${orderId}-not_invoiced`)).toBeVisible()
    await expect(page.getByTestId(`distributor-o2c-exception-${orderId}-delivery_incomplete`)).toHaveCount(0)

    // ── A reader with no sales, inventory or accounting access sees none of it ─
    const readerContext = await browser.newContext({ storageState: { cookies: [], origins: [] } })
    try {
      const readerPage = await readerContext.newPage()
      await signIn(readerPage, "fixture.reader@example.test", PERSONA_PASSWORD)
      await gotoModule(readerPage, "/distributor", "distributor")
      await readerPage.waitForLoadState("networkidle")
      await expect(readerPage.getByTestId(`distributor-o2c-row-${orderId}`)).toHaveCount(0)
    } finally {
      await readerContext.close()
    }
  })
})
