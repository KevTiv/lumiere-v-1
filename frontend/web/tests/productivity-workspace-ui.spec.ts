import { expect as baseExpect, test, type Page } from "@playwright/test"

const expect = baseExpect.configure({ timeout: 15_000 })
test.describe.configure({ timeout: 60_000 })
const browserErrors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
})
test.afterEach(({ page }) => {
  expect(browserErrors.get(page) ?? []).toEqual([])
})

async function ready(page: Page, href: string) {
  await page.goto(href, { waitUntil: "domcontentloaded" })
  await expect(page.getByTestId("productivity-disclosure")).toHaveAttribute("data-hydrated", "true")
}
async function contained(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
}

for (const width of [390, 1440]) {
  test(`files retain folder, search and exact selection at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 950 })
    const api: string[] = []
    page.on("request", (request) => { if (new URL(request.url()).pathname.startsWith("/api/")) api.push(request.url()) })
    await ready(page, "/productivity?panel=files")
    await page.getByTestId("file-browser-folder-7").click()
    await expect(page).toHaveURL(/folder=7/)
    await page.getByRole("textbox", { name: /^Search files/ }).fill("October")
    await expect(page).toHaveURL(/fileSearch=October/)
    await page.getByTestId("file-browser-layout-list").click()
    await expect(page).toHaveURL(/fileLayout=list/)
    await expect(page.getByTestId("file-browser-row-91")).toBeVisible()
    await expect(page.getByTestId("file-browser-row-92")).toHaveCount(0)
    await page.getByTestId("file-browser-row-91").click()
    await expect(page.getByTestId("synthetic-document")).toContainText("Document #91")
    await page.goBack({ waitUntil: "domcontentloaded" })
    await expect(page.getByRole("textbox", { name: /^Search files/ })).toHaveValue("October")
    await expect(page.getByTestId("file-browser-list")).toBeVisible()
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page.getByTestId("productivity-disclosure")).toHaveAttribute("data-hydrated", "true")
    await expect(page.getByTestId("file-browser-row-91")).toBeVisible()
    await page.getByTestId("file-browser-input").setInputFiles({ name: "receipt.pdf", mimeType: "application/pdf", buffer: Buffer.from("synthetic receipt") })
    await expect(page.getByTestId("file-browser-upload-results")).toContainText("receipt.pdf")
    await expect(page.getByTestId("file-browser-upload-results").getByRole("alert")).toContainText("Synthetic upload failure")
    await expect(page.getByTestId("file-browser-upload-results")).toContainText("Check the files list")
    await contained(page)
    await page.screenshot({ path: test.info().outputPath(`productivity-files-${width}.png`), fullPage: true })
    expect(api).toEqual([])
  })

  test(`calendar agenda preserves exact events and keyboard selection at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 950 })
    await ready(page, "/productivity?panel=calendar&date=2026-10-28&view=agenda")
    await expect(page.getByTestId("calendar-agenda")).toBeVisible()
    await expect(page.getByText("Times shown in Europe/Amsterdam", { exact: true })).toBeVisible()
    await expect(page.getByTestId("calendar-agenda-event-42")).toHaveCount(3)
    await expect(page.getByTestId("calendar-agenda-event-43")).toContainText("Cancelled")
    await expect(page.getByTestId("calendar-agenda-event-44")).toContainText("All day")
    const event = page.getByTestId("calendar-agenda-event-41")
    await event.focus()
    await page.keyboard.press("ArrowLeft")
    await expect(page.getByRole("dialog")).toHaveCount(0)
    await page.keyboard.press("Enter")
    await expect(page.getByRole("dialog")).toBeVisible()
    await expect(page.getByRole("dialog")).toContainText("Invoice review")
    await expect(page.getByTestId("calendar-event-open")).toHaveAttribute("href", "/calendar/events/41")
    await expect(page).toHaveURL(/event=41/)
    await page.keyboard.press("Escape")
    await expect(page.getByRole("dialog")).toHaveCount(0)
    await page.getByRole("button", { name: "New Event", exact: true }).click()
    await expect(page.getByTestId("synthetic-create-count")).toHaveText("Create callbacks: 1")
    await page.getByRole("button", { name: "Month", exact: true }).click()
    await expect(page).toHaveURL(/view=month/)
    await expect(page.locator("button button")).toHaveCount(0)
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page.getByTestId("productivity-disclosure")).toHaveAttribute("data-hydrated", "true")
    await expect(page.getByRole("button", { name: "Month", exact: true })).toHaveAttribute("aria-pressed", "true")
    await page.getByRole("button", { name: "Agenda", exact: true }).click()
    await contained(page)
    await page.screenshot({ path: test.info().outputPath(`productivity-calendar-${width}.png`), fullPage: true })
  })

  test(`conversation source boundaries, retained reply and context reset at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 950 })
    await ready(page, "/productivity?panel=messages")
    await expect(page.getByText("2 loaded conversations", { exact: true })).toBeVisible()
    await page.getByRole("button", { name: /Please review invoice INV-0041/ }).click()
    await expect(page).toHaveURL(/message=101/)
    await expect(page.getByTestId("conversation-messages")).toContainText("The receipt is attached")
    await expect(page.getByTestId("conversation-messages")).not.toContainText("Separate supplier discussion")
    await expect(page.locator('a[href="/messages/101"]').filter({ hasText: "Open message" })).toHaveAttribute("href", "/messages/101")
    await expect(page.locator('a[href="/accounting/invoices/41"]').filter({ hasText: "Open record" })).toHaveAttribute("href", /41/)
    const reply = page.getByRole("textbox", { name: /^Reply to this conversation/ })
    await reply.fill("Please confirm the receipt")
    await page.getByRole("button", { name: "Post reply", exact: true }).click()
    await expect(page.getByTestId("message-conversation-workspace").getByRole("alert")).toContainText("Synthetic rejection")
    await expect(reply).toContainText("Please confirm the receipt")
    await page.getByRole("button", { name: "Post reply", exact: true }).click()
    await expect(page.getByTestId("conversation-messages")).toContainText("Please confirm the receipt")
    await expect(page.getByTestId("reply-callback-count")).toContainText("Reply callbacks: 2")
    await expect(page).toHaveURL(/message=104/)
    await reply.fill("Private draft for current company")
    await contained(page)
    await page.screenshot({ path: test.info().outputPath(`productivity-messages-${width}.png`), fullPage: true })
    await page.getByRole("button", { name: "Switch preview company", exact: true }).click()
    await expect(page.getByTestId("message-conversation-workspace")).not.toContainText("Private draft for current company")
    await expect(page.getByTestId("message-conversation-workspace")).not.toContainText("Please review invoice INV-0041")
  })

  test(`uncertain reply checks outcome without reposting at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 950 })
    await ready(page, "/productivity?panel=messages&uncertain=1&message=101")
    const reply = page.getByRole("textbox", { name: /^Reply to this conversation/ })
    await reply.fill("Check the outcome of this exact attempt")
    await page.getByRole("button", { name: "Post reply", exact: true }).click()
    await expect(page.getByTestId("message-conversation-workspace").getByRole("alert")).toContainText("unconfirmed")
    await expect(page.getByRole("button", { name: "Post reply", exact: true })).toHaveCount(0)
    await page.getByRole("button", { name: "Check outcome", exact: true }).click()
    await expect(page.getByTestId("reply-callback-count")).toHaveText("Reply callbacks: 1; read callbacks: 1")
    await expect(page.getByTestId("conversation-messages")).toContainText("Check the outcome of this exact attempt")
  })

  test(`productivity grouped navigation keeps direct links at ${width}px`, async ({ page }) => {
    test.setTimeout(120_000)
    await page.setViewportSize({ width, height: 950 })
    for (const [module, group, tab] of [["documents", "files", "documents"], ["calendar", "schedule", "calendar"], ["messages", "conversations", "messages"]]) {
      await page.goto(`/navigation?module=${module}&company=7`, { waitUntil: "domcontentloaded" })
      await expect(page.getByTestId("navigation-disclosure")).toHaveAttribute("data-hydrated", "true")
      await expect(page.getByTestId(`module-workspace-${module}-${group}`)).toHaveAttribute("aria-current", "page")
      await expect(page.getByTestId(`module-tab-${module}-${tab}`)).toHaveAttribute("aria-selected", "true")
      await page.getByTestId(`module-workspace-${module}-overflow`).click()
      await page.getByRole("menuitem", { name: "dashboard", exact: true }).click()
      await expect(page).toHaveURL(/tab=dashboard/)
      await page.goBack({ waitUntil: "domcontentloaded" })
      await page.waitForURL((url) => !url.searchParams.has("tab"))
      await expect(page.getByTestId(`module-tab-${module}-${tab}`)).toHaveAttribute("aria-selected", "true")
      await page.goForward({ waitUntil: "domcontentloaded" })
      await page.waitForURL(/tab=dashboard/)
      await page.reload({ waitUntil: "domcontentloaded" })
      await expect(page.getByTestId(`module-view-${module}`)).toHaveAttribute("data-hydrated", "true")
      await expect(page.getByTestId(`module-tab-${module}-dashboard`)).toHaveAttribute("aria-selected", "true")
      await contained(page)
    }
  })
}
