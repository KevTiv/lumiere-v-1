#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = new URL("../", import.meta.url)
const requireContracts = createRequire(
  new URL("frontend/packages/stdb/package.json", root),
)
const { CANONICAL_RESOURCES } = await import(
  pathToFileURL(
    requireContracts.resolve("@lumiere/contracts/generated/resources"),
  ).href
)
const columns = JSON.parse(
  await readFile(
    requireContracts.resolve(
      "@lumiere/contracts/stdb-generated-sql-columns.json",
    ),
    "utf8",
  ),
)
const optionFields = JSON.parse(
  await readFile(
    new URL("frontend/packages/stdb/src/stdb-http-option-fields.json", root),
    "utf8",
  ),
)
const target = new URL(
  "frontend/web/hooks/stored-dashboard-resource-scope.generated.ts",
  root,
)

/** Native owner/parent/global reads retain their declared server authorization semantics. */
function scopeFor(resource) {
  const fields = columns[resource.rowTypeReference]
  if (!Array.isArray(fields))
    throw new Error(`Missing generated columns for ${resource.name}`)
  if (
    [
      "global",
      "identity",
      "organization_identity",
      "organization_via_parent",
    ].includes(resource.scope.kind)
  )
    return "native"
  if (fields.includes("company_id")) {
    return optionFields[resource.rowTypeReference]?.includes("company_id")
      ? "optional-company"
      : "company"
  }
  // Company scope through a nonstandard field or parent needs a native projection
  // before a browser aggregation can attest the selected company's full total.
  return resource.scope.company_field === null &&
    !resource.scope.kind.includes("company")
    ? "native"
    : "unknown"
}

const rows = [...CANONICAL_RESOURCES].sort((a, b) =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
)
const result = `// @generated by scripts/generate-dashboard-source-scope.mjs; do not edit.
// Inputs: pinned contract resources/SQL columns and generated STDB Option fields.
export type StoredDashboardResourceScope =
  | "native"
  | "company"
  | "optional-company"
  | "unknown"

export const STORED_DASHBOARD_RESOURCE_SCOPES: Readonly<
  Record<string, StoredDashboardResourceScope>
> = {
${rows.map((resource) => `  ${/^[a-zA-Z_$][\w$]*$/.test(resource.name) ? resource.name : JSON.stringify(resource.name)}: ${JSON.stringify(scopeFor(resource))},`).join("\n")}
}
`

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "")
  if (current !== result) {
    process.stderr.write(
      "Dashboard source scope metadata is stale. Run node scripts/generate-dashboard-source-scope.mjs.\n",
    )
    process.exitCode = 1
  } else {
    process.stdout.write(
      `Dashboard source scope metadata is current (${rows.length} resources).\n`,
    )
  }
} else {
  await writeFile(target, result)
  process.stdout.write(
    `Generated ${fileURLToPath(target)} (${rows.length} resources).\n`,
  )
}
