#!/usr/bin/env node
/** Validate the canonical C8 subscription census and emit its TypeScript view. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const censusPath = path.join(root, "crates/stdb-auth/assets/subscription-census.json");
const registryPath = path.join(root, "crates/stdb-auth/assets/resource_registry.json");
const rustKeysPath = path.join(root, "crates/stdb-auth/assets/subscription-resource-keys.json");
const rustFullPath = path.join(root, "crates/stdb-auth/assets/full-client-subscription-resources.json");
const generatedPath = path.join(root, "frontend/packages/stdb/src/generated/subscription-descriptors.ts");

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const census = readJson(censusPath);
const registry = readJson(registryPath);
const rustKeys = readJson(rustKeysPath);
const rustFull = readJson(rustFullPath);
const fail = (message) => {
  throw new Error(`[subscription-census] ${message}`);
};

function validate() {
  if (census.schemaVersion !== 1) fail("unsupported schemaVersion");
  if (
    census.authoritativeResourceSet?.source !== "crates/stdb-auth/assets/subscription-census.json:entries" ||
    census.authoritativeResourceSet.count !== census.entries?.length
  ) fail("canonical resource-set metadata is stale");

  const resources = census.entries.map(({ resource }) => resource);
  if (new Set(resources).size !== resources.length) fail("duplicate resource key");
  const virtualTables = {
    auth: "auth-session-bundle",
    "auth-role-table": "role",
    "org-permissions": "org_permission",
    "policy-snapshots": "policy_snapshot",
  };
  const allowed = {
    scope: new Set(["global", "organization", "company", "identity", "organization+identity", "organization+company"]),
    delivery: new Set(["invalidation-only", "bff-only"]),
    predicate: new Set(["none", "derived-queue", "field-policy-filter", "authorization-sensitive"]),
    cardinality: new Set(["one", "few", "bounded-page", "bounded-set", "broad"]),
    fanout: new Set(["low", "medium", "high"]),
    latency: new Set(["interactive", "background", "presence"]),
    reconnect: new Set(["eager", "staggered", "on-demand"]),
    access: new Set(["approved", "pending", "not-applicable", "exception"]),
  };

  for (const entry of census.entries) {
    const expectedTable = virtualTables[entry.resource] ?? registry[entry.resource]?.table;
    if (!expectedTable || entry.source?.table !== expectedTable) fail(`${entry.resource} source table drift`);
    if (!allowed.scope.has(entry.scope)) fail(`${entry.resource} has unsafe scope`);
    if (!allowed.delivery.has(entry.deliveryMode)) fail(`${entry.resource} has unsafe deliveryMode`);
    if (entry.directRowExposure !== false) fail(`${entry.resource} enables direct-row exposure`);
    if (!allowed.predicate.has(entry.predicateClass)) fail(`${entry.resource} has unknown predicate class`);
    if (!allowed.cardinality.has(entry.expectedCardinality)) fail(`${entry.resource} has invalid cardinality`);
    if (!allowed.fanout.has(entry.updateFanout)) fail(`${entry.resource} has invalid update fanout`);
    if (!allowed.latency.has(entry.latencyClass)) fail(`${entry.resource} has invalid latency class`);
    if (!allowed.reconnect.has(entry.reconnectClass)) fail(`${entry.resource} has invalid reconnect class`);
    if (!entry.accessPath?.exception || !allowed.access.has(entry.accessPath.status)) fail(`${entry.resource} has incomplete access-path classification`);
    if (
      entry.subscriptionApiAcceptance?.required !== true ||
      entry.subscriptionApiAcceptance.method !== "live-subscription-api" ||
      entry.subscriptionApiAcceptance.spacetimeSqlStringValidationEquivalent !== false
    ) fail(`${entry.resource} weakens the live acceptance boundary`);
    if (
      entry.rustCompatibility?.subscriptionResourceKeys !== rustKeys.includes(entry.resource) ||
      entry.rustCompatibility?.fullClientSubscriptionResources !== rustFull.includes(entry.resource)
    ) fail(`${entry.resource} Rust compatibility metadata is stale`);
  }
}

function generatedTypescript() {
  const descriptors = Object.fromEntries(census.entries.map((entry) => [entry.resource, {
    resource: entry.resource,
    source: entry.source,
    scope: entry.scope,
    deliveryMode: entry.deliveryMode,
    realtime: entry.deliveryMode !== "bff-only",
    directRowExposure: false,
    fieldSensitivity: entry.fieldSensitivity,
    predicateClass: entry.predicateClass,
    expectedCardinality: entry.expectedCardinality,
    latencyClass: entry.latencyClass,
    updateFanout: entry.updateFanout,
    sourceClass: entry.sourceClass,
    reconnectClass: entry.reconnectClass,
    accessPath: entry.accessPath,
  }]));
  const keys = census.entries.map(({ resource }) => resource);
  return `// @generated by scripts/generate-subscription-census.mjs — do not edit.\n` +
    `// Canonical input: crates/stdb-auth/assets/subscription-census.json\n\n` +
    `export const SUBSCRIPTION_DESCRIPTORS = ${JSON.stringify(descriptors, null, 2)} as const;\n\n` +
    `export const SUBSCRIPTION_RESOURCE_KEYS = ${JSON.stringify(keys, null, 2)} as const;\n\n` +
    `export type SubscriptionResourceKey = keyof typeof SUBSCRIPTION_DESCRIPTORS;\n`;
}

validate();
const expected = generatedTypescript();
const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  writeFileSync(generatedPath, expected);
  console.log(`[subscription-census] wrote ${census.entries.length} generated descriptors`);
} else if (mode === "--check") {
  let actual;
  try { actual = readFileSync(generatedPath, "utf8"); } catch { fail("generated descriptor module is missing; run with --write"); }
  if (actual !== expected) fail("generated descriptor module is stale; run with --write");
} else {
  fail("usage: --write or --check");
}
console.log(`[subscription-census] OK — ${census.entries.length} canonical entries`);
