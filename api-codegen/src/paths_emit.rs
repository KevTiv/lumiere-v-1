//! Emit `api-server-paths.ts` from OpenAPI `paths`.

use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::BTreeMap;

pub fn ts_fn_name_from_path(openapi_path: &str) -> String {
    let mut out = String::from("url");
    for seg in openapi_path.trim_start_matches('/').split('/') {
        if seg.is_empty() {
            continue;
        }
        if let Some(inner) = seg.strip_prefix('{').and_then(|s| s.strip_suffix('}')) {
            out.push_str(&to_pascal_segment(inner));
        } else {
            out.push_str(&to_pascal_segment(seg));
        }
    }
    out
}

pub fn path_suffix_for_hooks(openapi_path: &str) -> String {
    ts_fn_name_from_path(openapi_path)
        .strip_prefix("url")
        .unwrap_or("")
        .to_string()
}

fn to_pascal_segment(s: &str) -> String {
    s.split(|c: char| !c.is_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect()
}

/// TypeScript template literal expression (backticks) for the browser path.
fn client_path_expr(openapi_path: &str) -> String {
    if openapi_path == "/health" {
        return "`/health`".to_string();
    }
    if openapi_path == "/v1/openapi.json" {
        return "`/v1/openapi.json`".to_string();
    }
    let tail = openapi_path.strip_prefix("/v1").unwrap_or(openapi_path);
    let mut tmpl = String::from("/api");
    let mut i = 0usize;
    let s = tail;
    while i < s.len() {
        if s.as_bytes().get(i) == Some(&b'{') {
            let end = s[i..]
                .find('}')
                .map(|j| i + j)
                .expect("unclosed path parameter brace in OpenAPI path");
            let name = &s[i + 1..end];
            tmpl.push_str(&format!("${{enc({name})}}"));
            i = end + 1;
        } else {
            let start = i;
            while i < s.len() && s.as_bytes().get(i) != Some(&b'{') {
                i += 1;
            }
            tmpl.push_str(&s[start..i]);
        }
    }
    format!("`{tmpl}`")
}

pub fn path_param_names(openapi_path: &str) -> Vec<String> {
    openapi_path
        .split('/')
        .filter_map(|seg| {
            seg.strip_prefix('{')
                .and_then(|s| s.strip_suffix('}'))
                .map(|s| s.to_string())
        })
        .collect()
}

pub fn collect_query_params(path_item: &Value) -> Vec<(String, String)> {
    let mut map: BTreeMap<String, String> = BTreeMap::new();
    let Some(obj) = path_item.as_object() else {
        return vec![];
    };
    for op in obj.values() {
        let Some(op_obj) = op.as_object() else {
            continue;
        };
        let Some(params) = op_obj.get("parameters").and_then(|p| p.as_array()) else {
            continue;
        };
        for p in params {
            let Some(po) = p.as_object() else {
                continue;
            };
            if po.get("in").and_then(|x| x.as_str()) != Some("query") {
                continue;
            }
            let Some(name) = po.get("name").and_then(|x| x.as_str()) else {
                continue;
            };
            let ty = po
                .get("schema")
                .and_then(|s| s.get("type"))
                .and_then(|x| x.as_str())
                .unwrap_or("string");
            let ts = match ty {
                "integer" | "number" => "number",
                "boolean" => "boolean",
                _ => "string",
            };
            map.entry(name.to_string())
                .or_insert_with(|| ts.to_string());
        }
    }
    map.into_iter().collect()
}

pub fn emit_paths_typescript(doc: &Value) -> Result<String> {
    let paths = doc
        .get("paths")
        .and_then(|p| p.as_object())
        .context("OpenAPI paths missing")?;

    let mut lines: Vec<String> = vec![
        "// Auto-generated by `cargo run -p api-codegen`. Do not edit.".to_string(),
        "// Paths under `/v1/*` are emitted as `/api/*` for use with `apiFetch` / `apiUrl`."
            .to_string(),
        "".to_string(),
        "function enc(s: string | number | boolean): string {".to_string(),
        "  return encodeURIComponent(String(s))".to_string(),
        "}".to_string(),
        "".to_string(),
    ];

    let mut keys: Vec<_> = paths.keys().cloned().collect();
    keys.sort();

    for path in keys {
        let item = paths.get(&path).unwrap();
        let fn_name = ts_fn_name_from_path(&path);
        let path_params = path_param_names(&path);
        let query = collect_query_params(item);

        let mut args: Vec<String> = path_params
            .iter()
            .map(|n| format!("{n}: string | number"))
            .collect();

        if !query.is_empty() {
            let fields: Vec<String> = query.iter().map(|(n, t)| format!("  {n}?: {t}")).collect();
            args.push(format!("query?: {{\n{}\n}}", fields.join("\n")));
        }

        let sig = args.join(", ");
        let body_path = client_path_expr(&path);

        if path == "/v1/openapi.json" {
            lines.push(
                "/** OpenAPI `/v1/openapi.json` — use `getApiGatewayBaseUrl() + urlV1OpenapiJson()`; not rewritten by `apiUrl`. */"
                    .to_string(),
            );
        } else {
            lines.push(format!("/** OpenAPI `{path}` */"));
        }
        lines.push(format!("export function {fn_name}({sig}): string {{"));

        if query.is_empty() {
            lines.push(format!("  return {body_path}"));
        } else {
            lines.push(format!("  const out = {body_path}"));
            lines.push("  const q = new URLSearchParams()".to_string());
            for (name, _) in &query {
                let esc_name = serde_json::to_string(name).unwrap();
                lines.push(format!(
                    "  if (query?.{name} !== undefined && query?.{name} !== null) q.set({esc_name}, String(query.{name}))"
                ));
            }
            lines.push("  const qs = q.toString()".to_string());
            lines.push("  return qs ? `${out}?${qs}` : out".to_string());
        }

        lines.push("}".to_string());
        lines.push(String::new());
    }

    Ok(lines.join("\n"))
}
