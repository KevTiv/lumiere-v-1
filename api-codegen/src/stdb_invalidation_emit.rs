//! Emit `stdb-reducer-invalidation.ts` from `reducer-stdb-invalidation.json`.

use anyhow::{Context, Result};
use serde_json::Value;

pub fn emit_std_invalidation_typescript(manifest: &Value) -> Result<String> {
    let obj = manifest
        .as_object()
        .context("manifest root must be a JSON object")?;
    let mut reducers: Vec<_> = obj.iter().collect();
    reducers.sort_by(|a, b| a.0.cmp(b.0));

    let mut entries = Vec::new();
    for (reducer, val) in reducers {
        let arr = val
            .as_array()
            .with_context(|| format!("{reducer}: value must be a JSON array"))?;
        let mut parts = Vec::new();
        for item in arr {
            let s = item
                .as_str()
                .with_context(|| format!("{reducer}: array entries must be strings"))?;
            parts.push(serde_json::to_string(s).expect("string json"));
        }
        let reducer_lit = serde_json::to_string(reducer).expect("key json");
        entries.push(format!(
            "  {}: [{}] as const",
            reducer_lit,
            parts.join(", ")
        ));
    }

    Ok(format!(
        r#"// Auto-generated by `cargo run -p api-codegen`. Do not edit.
// Maps SpacetimeDB reducer names to `useStdbQuery` resource names for TanStack invalidation.

/** Resources to invalidate after a successful POST /api/call/{{reducer}} (same strings as useStdbQuery first arg). */
export const STDB_REDUCER_INVALIDATION: Record<string, readonly string[]> = {{
{}
}}

export function stdbInvalidationFor(reducer: string): readonly string[] {{
  const v = STDB_REDUCER_INVALIDATION[reducer]
  return v ?? []
}}
"#,
        entries.join(",\n")
    ))
}
