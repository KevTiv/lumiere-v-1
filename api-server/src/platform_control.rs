/// Insert a credential.  Email uniqueness is case-insensitive at the DB
/// boundary, and callers must supply the opaque binding ID explicitly.
pub async fn insert_user_credential(pool: &Pool, credential: &UserCredential) -> Result<()> {
    let client = pool
        .get()
        .await
        .context("get PG client for user credential")?;
    client
        .execute(
            "INSERT INTO lumiere_platform.user_credential \
             (platform_user_id, email, stdb_identity_hex, password_hash, workos_user_id, stdb_token_enc, email_verified) \
             VALUES ($1, $2, $3, $4, $5, $6, $7)",
            &[
                &credential.platform_user_id.as_str(),
                &credential.email,
                &credential.stdb_identity_hex,
                &credential.password_hash,
                &credential.workos_user_id,
                &credential.stdb_token_enc,
                &credential.email_verified,
            ],
        )
        .await
        .context("insert platform user credential")?;
    Ok(())
}

/// Update only the canonical password hash for a platform user.
///
/// Password material never crosses the SpacetimeDB binding boundary.  The
/// affected-row check also prevents silently accepting a reset for a missing
/// platform account.
pub async fn update_user_password(
    pool: &Pool,
    platform_user_id: &PlatformId,
    password_hash: &str,
) -> Result<bool> {
    let client = pool
        .get()
        .await
        .context("get PG client to update platform password")?;
    let changed = client
        .execute(
            "UPDATE lumiere_platform.user_credential SET password_hash = $2, updated_at = now() \
             WHERE platform_user_id = $1",
            &[&platform_user_id.as_str(), &password_hash],
        )
        .await
        .context("update platform password hash")?;
    Ok(changed == 1)
}

/// Register one active service binding and retire the previous binding for the
/// same service atomically.  This is intentionally a platform operation and
/// takes an opaque registrar ID rather than an organization ID.
pub async fn register_cold_tier_service_identity(
    pool: &Pool,
    identity: &ColdTierServiceIdentity,
) -> Result<i64> {
    let mut client = pool
        .get()
        .await
        .context("get PG client for service identity")?;
    let transaction = client
        .transaction()
        .await
        .context("begin service identity transaction")?;
    transaction
        .execute(
            "UPDATE lumiere_platform.cold_tier_service_identity \
             SET is_active = false, retired_at = now() \
             WHERE service_name = $1 AND is_active",
            &[&identity.service_name],
        )
        .await
        .context("retire prior platform service identity")?;
    let row = transaction
        .query_one(
            "INSERT INTO lumiere_platform.cold_tier_service_identity \
             (service_name, platform_id, stdb_identity_hex, registered_by) \
             VALUES ($1, $2, $3, $4) RETURNING id",
            &[
                &identity.service_name,
                &identity.platform_id.as_str(),
                &identity.stdb_identity_hex,
                &identity.registered_by.as_str(),
            ],
        )
        .await
        .context("insert platform service identity")?;
    transaction
        .commit()
        .await
        .context("commit service identity transaction")?;
    Ok(row.get("id"))
}

