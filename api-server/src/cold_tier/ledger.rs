//! Cross-tier archive transfer ledger.
//!
//! Every attempted archive transfer (PG UPSERT written, STDB row not yet
//! deleted) gets one row here, keyed by `(resource, row_id)`. This supports
//! auditability and disaster-recovery validation per the sliding-window plan
//! (`docs/plans/sliding-window-cold-tier.md` §6.3): independent PG/STDB
//! backups are not provably consistent without a record of which archive
//! transfers actually completed.
//!
//! One row per `(resource, row_id)` — re-attempts (retry after a crash, or a
//! racing duplicate projector/finalizer) UPSERT the same row rather than accumulating
//! history, since the ledger's job is "is this row's archive transfer
//! durable and finalized", not an append-only audit trail of attempts.

use anyhow::{bail, Context, Result};
use deadpool_postgres::Pool;

const MAX_PENDING_TRANSFERS: u32 = 200;

const RECORD_TRANSFER_SQL: &str = "INSERT INTO archive_transfer \
        (resource, row_id, organization_id, archive_version, payload_checksum, pg_transferred_at) \
     VALUES ($1, $2::TEXT::NUMERIC, $3::TEXT::NUMERIC, $4, $5, now()) \
     ON CONFLICT (resource, row_id) DO UPDATE SET \
        pg_transferred_at = archive_transfer.pg_transferred_at \
     WHERE archive_transfer.organization_id = EXCLUDED.organization_id \
       AND archive_transfer.archive_version = EXCLUDED.archive_version \
       AND archive_transfer.payload_checksum = EXCLUDED.payload_checksum";
const EXISTING_TRANSFER_SQL: &str =
    "SELECT organization_id::TEXT, archive_version, payload_checksum \
     FROM archive_transfer \
     WHERE resource = $1 AND row_id = $2::TEXT::NUMERIC";
const MARK_FINALIZED_SQL: &str = "UPDATE archive_transfer SET stdb_finalized_at = now() \
     WHERE resource = $1 AND row_id = $2::TEXT::NUMERIC AND stdb_finalized_at IS NULL";
const PENDING_TRANSFERS_SQL: &str =
    "SELECT resource, row_id::TEXT, organization_id::TEXT, archive_version, payload_checksum \
     FROM archive_transfer \
     WHERE resource = $1 AND stdb_finalized_at IS NULL \
     ORDER BY pg_transferred_at ASC, row_id ASC \
     LIMIT $2";

/// A durable archive transfer whose STDB source row has not been marked deleted.
///
/// Numeric identifiers remain strings because the ledger schema uses
/// `NUMERIC(20,0)` and reconciliation must not narrow a durable value before
/// the caller has validated its domain-specific range.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PendingTransfer {
    pub resource: String,
    pub row_id: String,
    pub organization_id: String,
    pub archive_version: i64,
    pub payload_checksum: String,
}

/// DDL for the `archive_transfer` table. Applied by
/// [`crate::cold_tier::migrate::ensure_schema`]; not generated by
/// `lumiere-codegen` since it is shared infrastructure, not a per-resource
/// cold table.
pub const ARCHIVE_TRANSFER_DDL: &str = r#"
CREATE TABLE IF NOT EXISTS archive_transfer (
    resource TEXT NOT NULL,
    row_id NUMERIC(20,0) NOT NULL,
    organization_id NUMERIC(20,0) NOT NULL,
    archive_version BIGINT NOT NULL,
    payload_checksum TEXT NOT NULL,
    pg_transferred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    stdb_finalized_at TIMESTAMPTZ,
    CONSTRAINT archive_transfer_pkey PRIMARY KEY (resource, row_id)
);

CREATE INDEX IF NOT EXISTS archive_transfer_org ON archive_transfer (organization_id);
"#;

/// Record that `resource`/`row_id` was UPSERTed into its cold table with the
/// exact immutable transfer identity. Exact retries are idempotent; a retry
/// with a different organization, archive version, or checksum fails closed
/// and cannot overwrite the existing ledger row.
pub async fn record_transfer(
    pool: &Pool,
    resource: &str,
    row_id: &str,
    organization_id: &str,
    archive_version: i64,
    payload_checksum: &str,
) -> Result<()> {
    let client = pool
        .get()
        .await
        .context("get PG client for record_transfer")?;
    let affected = client
        .execute(
            RECORD_TRANSFER_SQL,
            &[
                &resource,
                &row_id,
                &organization_id,
                &archive_version,
                &payload_checksum,
            ],
        )
        .await
        .context("insert/update archive_transfer row")?;
    if affected == 0 {
        let existing = client
            .query_opt(EXISTING_TRANSFER_SQL, &[&resource, &row_id])
            .await
            .context("read conflicting archive_transfer row")?
            .ok_or_else(|| {
                anyhow::anyhow!(
                    "archive_transfer {resource}/{row_id} disappeared during compare-and-set"
                )
            })?;
        let existing_organization_id: String = existing.get(0);
        let existing_archive_version: i64 = existing.get(1);
        let existing_checksum: String = existing.get(2);
        bail!(
            "archive_transfer {resource}/{row_id} identity mismatch: existing organization/version/checksum {existing_organization_id}/{existing_archive_version}/{existing_checksum}, requested {organization_id}/{archive_version}/{payload_checksum}"
        );
    }
    Ok(())
}

/// Mark `resource`/`row_id`'s transfer as finalized (the STDB row has been
/// deleted). Idempotent when the ledger row exists, including when it was
/// already marked; missing ledger rows fail closed.
pub async fn mark_finalized(pool: &Pool, resource: &str, row_id: &str) -> Result<()> {
    let client = pool
        .get()
        .await
        .context("get PG client for mark_finalized")?;
    let affected = client
        .execute(MARK_FINALIZED_SQL, &[&resource, &row_id])
        .await
        .context("mark archive_transfer finalized")?;
    if affected == 0 {
        let exists = client
            .query_opt(
                "SELECT 1 FROM archive_transfer WHERE resource = $1 AND row_id = $2::TEXT::NUMERIC",
                &[&resource, &row_id],
            )
            .await
            .context("verify archive_transfer exists after finalize")?;
        if exists.is_none() {
            bail!("cannot mark missing archive_transfer {resource}/{row_id} finalized");
        }
    }
    Ok(())
}

/// Read a bounded batch of transfers whose STDB deletion is still pending.
pub async fn pending_transfers(
    pool: &Pool,
    resource: &str,
    limit: u32,
) -> Result<Vec<PendingTransfer>> {
    if limit == 0 || limit > MAX_PENDING_TRANSFERS {
        bail!("pending archive transfer limit must be in 1..={MAX_PENDING_TRANSFERS}");
    }
    let client = pool
        .get()
        .await
        .context("get PG client for pending_transfers")?;
    let limit = i64::from(limit);
    let rows = client
        .query(PENDING_TRANSFERS_SQL, &[&resource, &limit])
        .await
        .context("read pending archive transfers")?;
    rows.into_iter()
        .map(|row| {
            Ok(PendingTransfer {
                resource: row.get(0),
                row_id: row.get(1),
                organization_id: row.get(2),
                archive_version: row.get(3),
                payload_checksum: row.get(4),
            })
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cold_tier::{conventions, migrate, pg_pool};
    use std::sync::atomic::{AtomicU64, Ordering};
    use std::time::{SystemTime, UNIX_EPOCH};

    static DATABASE_SEQUENCE: AtomicU64 = AtomicU64::new(0);

    #[test]
    fn ddl_creates_expected_table_and_index() {
        assert!(ARCHIVE_TRANSFER_DDL.contains("CREATE TABLE IF NOT EXISTS archive_transfer"));
        assert!(ARCHIVE_TRANSFER_DDL
            .contains("CONSTRAINT archive_transfer_pkey PRIMARY KEY (resource, row_id)"));
        assert!(ARCHIVE_TRANSFER_DDL.contains("CREATE INDEX IF NOT EXISTS archive_transfer_org"));
    }

    #[test]
    fn record_transfer_uses_exact_compare_and_set_identity() {
        assert!(RECORD_TRANSFER_SQL.contains("organization_id = EXCLUDED.organization_id"));
        assert!(RECORD_TRANSFER_SQL.contains("archive_version = EXCLUDED.archive_version"));
        assert!(RECORD_TRANSFER_SQL.contains("payload_checksum = EXCLUDED.payload_checksum"));
        assert!(
            RECORD_TRANSFER_SQL.contains("pg_transferred_at = archive_transfer.pg_transferred_at")
        );
        assert!(!RECORD_TRANSFER_SQL.contains("organization_id = EXCLUDED.organization_id,"));
        assert!(!RECORD_TRANSFER_SQL.contains("archive_version = EXCLUDED.archive_version,"));
        assert!(!RECORD_TRANSFER_SQL.contains("payload_checksum = EXCLUDED.payload_checksum,"));
    }

    #[test]
    fn pending_reader_is_bounded_and_excludes_finalized_rows() {
        assert!(PENDING_TRANSFERS_SQL.contains("stdb_finalized_at IS NULL"));
        assert!(PENDING_TRANSFERS_SQL.contains("ORDER BY pg_transferred_at ASC, row_id ASC"));
        assert!(PENDING_TRANSFERS_SQL.contains("LIMIT $2"));
        assert!(MAX_PENDING_TRANSFERS > 0);
    }

    #[test]
    fn mark_finalized_uses_pending_only_update() {
        assert!(MARK_FINALIZED_SQL.contains("stdb_finalized_at IS NULL"));
        assert!(MARK_FINALIZED_SQL.contains("resource = $1"));
        assert!(MARK_FINALIZED_SQL.contains("row_id = $2::TEXT::NUMERIC"));
    }

    #[tokio::test]
    async fn postgres_transfer_ledger_is_compare_and_set_and_reconcilable() -> Result<()> {
        if std::env::var("C5_TEST_PG").as_deref() != Ok("1") {
            eprintln!(
                "skipping postgres_transfer_ledger_is_compare_and_set_and_reconcilable \
                 (set C5_TEST_PG=1 to run)"
            );
            return Ok(());
        }

        let base_config =
            pg_pool::PgConfig::from_env().context("load C5 PostgreSQL test config")?;
        let database = unique_database_name()?;
        let admin_pool = admin_pool(&base_config)?;
        create_database(&admin_pool, &database, &base_config.user).await?;
        let mut test_config = base_config.clone();
        test_config.database.clone_from(&database);
        let pool = pg_pool::build_pool(&test_config).context("build C5 PostgreSQL test pool")?;
        let test_result = exercise_postgres_ledger(&pool).await;
        drop(pool);
        let cleanup_result = drop_database(&admin_pool, &database).await;
        test_result?;
        cleanup_result?;
        Ok(())
    }

    #[tokio::test]
    async fn postgres_rejects_malformed_transfer_ledger() -> Result<()> {
        if std::env::var("C5_TEST_PG").as_deref() != Ok("1") {
            eprintln!(
                "skipping postgres_rejects_malformed_transfer_ledger \
                 (set C5_TEST_PG=1 to run)"
            );
            return Ok(());
        }

        let base_config =
            pg_pool::PgConfig::from_env().context("load C5 PostgreSQL test config")?;
        let database = unique_database_name()?;
        let admin_pool = admin_pool(&base_config)?;
        create_database(&admin_pool, &database, &base_config.user).await?;
        let mut test_config = base_config.clone();
        test_config.database.clone_from(&database);
        let pool = pg_pool::build_pool(&test_config).context("build C5 PostgreSQL test pool")?;

        let client = pool.get().await?;
        client
            .batch_execute("CREATE TABLE archive_transfer (resource TEXT NOT NULL)")
            .await?;
        drop(client);
        let migration = migrate::ensure_schema(&pool).await;
        drop(pool);
        let cleanup_result = drop_database(&admin_pool, &database).await;
        assert!(
            migration
                .as_ref()
                .is_err_and(|error| error.to_string().contains("archive_transfer")),
            "malformed archive_transfer unexpectedly passed validation: {migration:?}"
        );
        cleanup_result?;
        Ok(())
    }

    async fn exercise_postgres_ledger(pool: &Pool) -> Result<()> {
        migrate::ensure_schema(pool).await?;
        let resource = "c5_test_resource";
        let row_id = format!("900000000000{}", std::process::id());
        let organization_id = "42";
        let client = pool.get().await?;
        client
            .execute(
                "DELETE FROM archive_transfer WHERE resource = $1 AND row_id = $2::TEXT::NUMERIC",
                &[&resource, &row_id],
            )
            .await?;
        drop(client);

        record_transfer(pool, resource, &row_id, organization_id, 7, "checksum-v7").await?;
        record_transfer(pool, resource, &row_id, organization_id, 7, "checksum-v7").await?;
        let conflict =
            record_transfer(pool, resource, &row_id, organization_id, 8, "checksum-v8").await;
        assert!(conflict.is_err());

        let pending = pending_transfers(pool, resource, 10).await?;
        assert_eq!(pending.len(), 1);
        assert_eq!(pending[0].row_id, row_id);
        assert_eq!(pending[0].archive_version, 7);
        assert_eq!(pending[0].payload_checksum, "checksum-v7");

        mark_finalized(pool, resource, &row_id).await?;
        mark_finalized(pool, resource, &row_id).await?;
        assert!(pending_transfers(pool, resource, 10).await?.is_empty());

        let client = pool.get().await?;
        client
            .execute(
                "DELETE FROM archive_transfer WHERE resource = $1 AND row_id = $2::TEXT::NUMERIC",
                &[&resource, &row_id],
            )
            .await?;
        Ok(())
    }

    fn unique_database_name() -> Result<String> {
        let micros = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .context("read clock for C5 PostgreSQL database")?
            .as_micros();
        let sequence = DATABASE_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        Ok(format!(
            "lumiere_c5_{}_{}_{}",
            std::process::id(),
            micros,
            sequence
        ))
    }

    fn admin_pool(config: &pg_pool::PgConfig) -> Result<Pool> {
        let mut admin = config.clone();
        admin.database = "postgres".to_string();
        pg_pool::build_pool(&admin)
    }

    async fn create_database(pool: &Pool, database: &str, owner: &str) -> Result<()> {
        let client = pool.get().await?;
        let database = conventions::quote_identifier(database)?;
        let owner = conventions::quote_identifier(owner)?;
        client
            .batch_execute(&format!("create database {database} owner {owner}"))
            .await
            .context("create disposable C5 PostgreSQL database")
    }

    async fn drop_database(pool: &Pool, database: &str) -> Result<()> {
        let client = pool.get().await?;
        client
            .query(
                "select pg_terminate_backend(pid) from pg_stat_activity \
                 where datname = $1 and pid <> pg_backend_pid()",
                &[&database],
            )
            .await?;
        let database = conventions::quote_identifier(database)?;
        client
            .batch_execute(&format!("drop database {database}"))
            .await
            .context("drop disposable C5 PostgreSQL database")
    }
}
