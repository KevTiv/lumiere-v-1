//! Hydration manifest generator.
//!
//! Reads `lumiere-codegen/hydration-policies.json`, validates each policy
//! against the schema IR, and emits `crates/stdb-auth/assets/hydration-manifest.json`.
//!
//! ## Purpose
//!
//! A hydration policy declares that a reducer may target an archived row by
//! id.  At call time the api-server checks whether the target row is absent
//! from STDB; if so it hydrates the row from PG before invoking the reducer
//! (see sliding-window-cold-tier.md §7).  The manifest is the codegen-checked
//! source of truth for which reducers need this orchestration.
//!
//! ## Validation performed
//!
//! 1. `reducer` is non-empty.
//! 2. `table` exists in the schema manifest and is one of the archive
//!    candidates (the row must be archive-capable for hydration to apply).
//! 3. `id_arg` is a non-empty dotted path beginning with `args.`
//!    (e.g. `"args.move_id"`).
//!
//! Full reducer-argument validation (does `args.move_id` exist on the named
//! reducer, with the right type?) is deferred until the reducer manifest is
//! introduced as part of the offline-sync work; the schema IR today only
//! covers tables and enums, not reducer signatures.

use anyhow::{bail, Context, Result};
use serde_json::Value;

use crate::schema_ir::LumiereSchemaManifest;

/// Emit the validated hydration manifest JSON.
///
/// `policies_json` is the raw `hydration-policies.json` text.  `archive_tables`
/// is the set of table names that are active archive candidates (from
/// `archive-candidates.json`); a policy must reference one of these, since
/// hydration only applies to archive-capable rows.
pub fn emit_hydration_manifest(
    policies_json: &str,
    schema_manifest: &LumiereSchemaManifest,
    archive_tables: &[String],
) -> Result<String> {
    let config: Value =
        serde_json::from_str(policies_json).context("parse hydration-policies.json")?;

    let policies = config["policies"]
        .as_array()
        .context("hydration-policies.json: missing 'policies' array")?;

    let mut out: Vec<Value> = Vec::with_capacity(policies.len());

    for (i, p) in policies.iter().enumerate() {
        let reducer = p["reducer"]
            .as_str()
            .with_context(|| format!("policies[{i}].reducer is not a string"))?;
        let table = p["table"]
            .as_str()
            .with_context(|| format!("policies[{i}].table is not a string"))?;
        let id_arg = p["id_arg"]
            .as_str()
            .with_context(|| format!("policies[{i}].id_arg is not a string"))?;

        if reducer.trim().is_empty() {
            bail!("policies[{i}]: reducer must not be empty");
        }
        if table.trim().is_empty() {
            bail!("policies[{i}]: table must not be empty");
        }
        if id_arg.trim().is_empty() {
            bail!("policies[{i}] (reducer '{reducer}'): id_arg must not be empty");
        }
        if !id_arg.trim().starts_with("args.") {
            bail!(
                "policies[{i}] (reducer '{reducer}'): id_arg '{id_arg}' must be a dotted \
                 path beginning with 'args.' (e.g. 'args.move_id')"
            );
        }

        // The table must exist in the schema manifest.
        if !schema_manifest.tables.iter().any(|t| t.sql_name == table) {
            bail!(
                "policies[{i}] (reducer '{reducer}'): table '{table}' not found in \
                 schema manifest. Re-run `make generate-stdb-rust-sdk && make codegen`."
            );
        }

        // The table must be an active archive candidate.
        if !archive_tables.iter().any(|t| t == table) {
            bail!(
                "policies[{i}] (reducer '{reducer}'): table '{table}' is not an active \
                 archive candidate. Hydration only applies to archive-capable tables."
            );
        }

        out.push(serde_json::json!({
            "reducer": reducer,
            "table": table,
            "id_arg": id_arg,
        }));
    }

    let manifest = serde_json::json!({
        "version": 1,
        "_comment": "Auto-generated by lumiere-codegen from hydration-policies.json. Do not edit.",
        "policies": out,
    });

    serde_json::to_string_pretty(&manifest).context("serialise hydration manifest")
}

