#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema_ir::*;

    fn manifest_with(table: &str) -> LumiereSchemaManifest {
        LumiereSchemaManifest {
            version: 1,
            tables: vec![GeneratedTableSchema {
                rust_name: "SaleOrder".into(),
                sql_name: table.to_string(),
                primary_key: GeneratedPrimaryKey {
                    column_name: "id".into(),
                    ty: GeneratedType::U64,
                },
                columns: vec![GeneratedColumn {
                    name: "id".into(),
                    sql_name: "id".into(),
                    ty: GeneratedType::U64,
                    nullable: false,
                }],
                indexes: vec![],
            }],
            enum_types: vec![],
        }
    }

    #[test]
    fn empty_policies_emit_empty_manifest() {
        let m = manifest_with("sale_order");
        let json = r#"{"version":1,"policies":[]}"#;
        let out = emit_hydration_manifest(json, &m, &["sale_order".to_string()]).unwrap();
        let parsed: Value = serde_json::from_str(&out).unwrap();
        assert_eq!(parsed["version"], 1);
        assert_eq!(parsed["policies"].as_array().unwrap().len(), 0);
    }

    #[test]
    fn valid_policy_emits_entry() {
        let m = manifest_with("sale_order");
        let json = r#"{"version":1,"policies":[{"reducer":"confirm_sale_order","table":"sale_order","id_arg":"args.order_id"}]}"#;
        let out = emit_hydration_manifest(json, &m, &["sale_order".to_string()]).unwrap();
        let parsed: Value = serde_json::from_str(&out).unwrap();
        assert_eq!(parsed["policies"][0]["reducer"], "confirm_sale_order");
        assert_eq!(parsed["policies"][0]["table"], "sale_order");
        assert_eq!(parsed["policies"][0]["id_arg"], "args.order_id");
    }

    #[test]
    fn rejects_empty_reducer() {
        let m = manifest_with("sale_order");
        let json =
            r#"{"version":1,"policies":[{"reducer":"","table":"sale_order","id_arg":"args.id"}]}"#;
        assert!(emit_hydration_manifest(json, &m, &["sale_order".to_string()]).is_err());
    }

    #[test]
    fn rejects_bad_id_arg_path() {
        let m = manifest_with("sale_order");
        let json = r#"{"version":1,"policies":[{"reducer":"r","table":"sale_order","id_arg":"order_id"}]}"#;
        assert!(emit_hydration_manifest(json, &m, &["sale_order".to_string()]).is_err());
    }

    #[test]
    fn rejects_table_not_in_schema() {
        let m = manifest_with("sale_order");
        let json =
            r#"{"version":1,"policies":[{"reducer":"r","table":"missing","id_arg":"args.id"}]}"#;
        assert!(emit_hydration_manifest(json, &m, &["sale_order".to_string()]).is_err());
    }

    #[test]
    fn rejects_table_not_an_archive_candidate() {
        let m = manifest_with("sale_order");
        let json =
            r#"{"version":1,"policies":[{"reducer":"r","table":"sale_order","id_arg":"args.id"}]}"#;
        // sale_order exists in schema but is not in the active archive list.
        assert!(emit_hydration_manifest(json, &m, &[]).is_err());
    }
}
