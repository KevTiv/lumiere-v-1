//! Versioned durable PostgreSQL schema generation.
//!
//! The projection codec describes how a row is encoded.  This module describes
//! the durable relation that receives that row and emits the first versioned
//! migration for it.  The storage-policy manifest remains the authority for
//! whether a table is locally durable and which access path it requires; the
//! schema IR remains the authority for columns, keys, and generated indexes.
//!
//! External-reference policies are represented in the manifest but deliberately
//! do not get a local PostgreSQL relation.  Their data is owned by an external
//! or platform source and creating an empty local table would make that
//! boundary ambiguous.

use anyhow::{bail, Context, Result};
use serde_json::{Map, Value};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

use super::codec_emit::durable_pg_type;
use crate::cold_tier::schema_ir::{GeneratedTableSchema, LumiereSchemaManifest};

#[cfg(test)]
pub const DURABLE_MIGRATION_VERSION: u32 = 1;
#[cfg(test)]
pub const DURABLE_MIGRATION_NAME: &str = "0001_durable_projection";
const PARTITION_MODULUS: u32 = 16;

/// The generated artifacts for one durable-schema migration.
#[cfg(test)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DurableMigrationArtifacts {
    pub sql: String,
    pub manifest: String,
    pub sql_checksum: String,
    pub applicable_table_count: usize,
}

/// Emit a versioned migration and its checksum-bearing schema manifest.
///
/// The policy list must cover every schema table exactly once.  Tables with an
/// `external-reference` projection are retained in the JSON manifest with
/// `applicable: false`, while all other policies produce a local relation.
#[cfg(test)]
pub fn emit_durable_migration(
    schema_manifest: &LumiereSchemaManifest,
    storage_policy_manifest: &Value,
) -> Result<DurableMigrationArtifacts> {
    let rendered = render_schema(schema_manifest, storage_policy_manifest)?;
    let sql_body: String = rendered.blocks.values().cloned().collect();
    let body_checksum = checksum(&sql_body);
    let sql = migration_file(
        DURABLE_MIGRATION_VERSION,
        DURABLE_MIGRATION_NAME,
        &body_checksum,
        &sql_body,
    );
    let sql_checksum = checksum(&sql);
    let manifest = serde_json::json!({
        "version": 1,
        "_comment": "Auto-generated by lumiere-codegen. Do not edit.",
        "checksum_algo": "sha256",
        "canonical_serialization": "utf8_sql_lf_exact_artifact",
        "migration": {
            "version": DURABLE_MIGRATION_VERSION,
            "name": DURABLE_MIGRATION_NAME,
            "sql_file": format!("manifests/pg_ddl/migrations/{DURABLE_MIGRATION_NAME}.sql"),
            "checksum": sql_checksum,
            "table_count": rendered.applicable_table_count,
            "policy_count": rendered.policy_count,
        },
        "tables": Value::Object(rendered.table_entries),
    });

    Ok(DurableMigrationArtifacts {
        sql,
        manifest: serde_json::to_string_pretty(&manifest)
            .context("serialise durable schema manifest")?,
        sql_checksum,
        applicable_table_count: rendered.applicable_table_count,
    })
}

struct RenderedSchema {
    /// Applicable tables only, in table-name order; each value is the exact
    /// block `render_table_sql` produced (it starts with its header comment).
    blocks: BTreeMap<String, String>,
    table_entries: Map<String, Value>,
    applicable_table_count: usize,
    policy_count: usize,
}

fn render_schema(
    schema_manifest: &LumiereSchemaManifest,
    storage_policy_manifest: &Value,
) -> Result<RenderedSchema> {
    let policies = storage_policies(storage_policy_manifest)?;
    let schema_by_name = schema_manifest
        .tables
        .iter()
        .map(|table| (table.sql_name.as_str(), table))
        .collect::<BTreeMap<_, _>>();

    if policies.len() != schema_by_name.len() {
        bail!(
            "durable schema requires one storage policy per schema table: {} policies for {} tables",
            policies.len(),
            schema_by_name.len()
        );
    }

    // The API-server migration runner supplies the transaction and advisory
    // lock.  Keeping the generated artifact to DDL statements also makes it
    // usable by migration tooling that wraps each version in its own tx.
    let mut blocks = BTreeMap::new();
    let mut table_entries = Map::new();
    let mut applicable_table_count = 0;

    for (table_name, policy) in &policies {
        let schema = schema_by_name.get(table_name.as_str()).with_context(|| {
            format!("storage policy references unknown schema table '{table_name}'")
        })?;
        validate_identifier(table_name)?;
        let applicable = policy_projection_mode(policy)? != "external-reference";
        let table_sql = render_table_sql(schema, policy, applicable)?;
        let table_checksum = checksum(&table_sql);
        if applicable {
            blocks.insert(table_name.clone(), table_sql);
            applicable_table_count += 1;
        }
        table_entries.insert(
            table_name.clone(),
            table_manifest_entry(schema, policy, applicable, &table_checksum)?,
        );
    }
    Ok(RenderedSchema {
        blocks,
        table_entries,
        applicable_table_count,
        policy_count: policies.len(),
    })
}

fn migration_file(version: u32, name: &str, body_checksum: &str, body: &str) -> String {
    format!(
        "-- Auto-generated by lumiere-codegen. Do not edit.\n\
         -- Migration version: {version}\n\
         -- Migration name: {name}\n\
         -- Checksum algorithm: sha256\n\
         -- Body checksum: {body_checksum}\n\n{body}"
    )
}

/// A migration that has been published and is therefore frozen.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReleasedMigration {
    pub version: u32,
    pub name: String,
    /// The exact published artifact, header included.
    pub sql: String,
}

/// Released durable migrations plus the version/name the next follow-up takes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MigrationLedger {
    pub released: Vec<ReleasedMigration>,
    pub pending_version: u32,
    pub pending_name: String,
}

impl MigrationLedger {
    /// Load `ledger.json` and the released files it names from `dir`.
    pub fn load(dir: &std::path::Path) -> Result<Self> {
        let ledger_path = dir.join("ledger.json");
        let ledger_json = std::fs::read_to_string(&ledger_path)
            .with_context(|| format!("read {}", ledger_path.display()))?;
        Self::parse(&ledger_json, |file| {
            let path = dir.join(file);
            std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))
        })
    }

    fn parse(ledger_json: &str, read: impl Fn(&str) -> Result<String>) -> Result<Self> {
        let ledger: Value =
            serde_json::from_str(ledger_json).context("parse durable migration ledger")?;
        if ledger["version"] != 1 {
            bail!("durable migration ledger version must be 1");
        }
        let entries = ledger["released"]
            .as_array()
            .context("durable migration ledger lacks a 'released' array")?;
        if entries.is_empty() {
            bail!("durable migration ledger must contain the released baseline migration");
        }
        let mut released = Vec::new();
        for entry in entries {
            let version = entry["version"]
                .as_u64()
                .and_then(|value| u32::try_from(value).ok())
                .context("released migration lacks a numeric version")?;
            let name = entry["name"]
                .as_str()
                .context("released migration lacks a name")?;
            let file = entry["file"]
                .as_str()
                .context("released migration lacks a file")?;
            if file != format!("{name}.sql") {
                bail!("released migration {version} file '{file}' must be '{name}.sql'");
            }
            if released
                .last()
                .map_or(version != 1, |last: &ReleasedMigration| version <= last.version)
            {
                bail!("released migrations must start at 1 and strictly increase (got {version})");
            }
            let sql = read(file)?;
            verify_released_artifact(version, name, &sql)?;
            released.push(ReleasedMigration {
                version,
                name: name.to_string(),
                sql,
            });
        }
        let pending_version = ledger["pending"]["version"]
            .as_u64()
            .and_then(|value| u32::try_from(value).ok())
            .context("ledger pending migration lacks a numeric version")?;
        let pending_name = ledger["pending"]["name"]
            .as_str()
            .context("ledger pending migration lacks a name")?
            .to_string();
        if pending_version <= released.last().map_or(0, |last| last.version) {
            bail!("pending migration version must follow the last released version");
        }
        Ok(Self {
            released,
            pending_version,
            pending_name,
        })
    }
}

/// A frozen file must still be a well-formed generated artifact: its header
/// names the migration and its body checksum matches the body.
fn verify_released_artifact(version: u32, name: &str, sql: &str) -> Result<()> {
    let (header, body) = sql
        .split_once("\n\n")
        .with_context(|| format!("released migration {version} has no header/body separator"))?;
    let expect = |line: String| -> Result<()> {
        if header.lines().any(|candidate| candidate == line) {
            Ok(())
        } else {
            bail!("released migration {version} header lacks '{line}'")
        }
    };
    expect(format!("-- Migration version: {version}"))?;
    expect(format!("-- Migration name: {name}"))?;
    expect(format!("-- Body checksum: {}", checksum(body)))
}

/// One migration file the generator emits.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmittedMigration {
    pub version: u32,
    pub name: String,
    pub sql: String,
    pub checksum: String,
    pub released: bool,
}

/// The released baseline re-emitted verbatim, an optional pending follow-up,
/// and the schema manifest that describes the complete current schema.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DurableMigrationSet {
    pub migrations: Vec<EmittedMigration>,
    pub manifest: String,
    pub applicable_table_count: usize,
}

const TABLE_HEADER: &str = "-- Durable projection: ";
const DELTA_HEADER: &str = "-- Durable projection delta: ";

/// Emit the durable schema as the frozen released migrations plus one pending
/// follow-up for whatever the current schema adds on top of them.
///
/// The manifest's `migration` object keeps describing the baseline (version 1)
/// so databases that recorded it still match; `migrations` lists every file.
pub fn emit_durable_migrations(
    schema_manifest: &LumiereSchemaManifest,
    storage_policy_manifest: &Value,
    ledger: &MigrationLedger,
) -> Result<DurableMigrationSet> {
    let rendered = render_schema(schema_manifest, storage_policy_manifest)?;
    let covered = covered_lines(&ledger.released)?;
    let delta_body = pending_delta_body(&covered, &rendered.blocks)?;

    let mut migrations: Vec<EmittedMigration> = ledger
        .released
        .iter()
        .map(|released| EmittedMigration {
            version: released.version,
            name: released.name.clone(),
            sql: released.sql.clone(),
            checksum: checksum(&released.sql),
            released: true,
        })
        .collect();
    if !delta_body.is_empty() {
        let sql = migration_file(
            ledger.pending_version,
            &ledger.pending_name,
            &checksum(&delta_body),
            &delta_body,
        );
        migrations.push(EmittedMigration {
            version: ledger.pending_version,
            name: ledger.pending_name.clone(),
            checksum: checksum(&sql),
            sql,
            released: false,
        });
    }

    let baseline = &migrations[0];
    let manifest = serde_json::json!({
        "version": 1,
        "_comment": "Auto-generated by lumiere-codegen. Do not edit.",
        "checksum_algo": "sha256",
        "canonical_serialization": "utf8_sql_lf_exact_artifact",
        "migration": {
            "version": baseline.version,
            "name": baseline.name,
            "sql_file": format!("manifests/pg_ddl/migrations/{}.sql", baseline.name),
            "checksum": baseline.checksum,
            "table_count": rendered.applicable_table_count,
            "policy_count": rendered.policy_count,
        },
        "migrations": migrations.iter().map(|migration| serde_json::json!({
            "version": migration.version,
            "name": migration.name,
            "sql_file": format!("manifests/pg_ddl/migrations/{}.sql", migration.name),
            "checksum": migration.checksum,
            "state": if migration.released { "released" } else { "pending" },
        })).collect::<Vec<_>>(),
        "tables": Value::Object(rendered.table_entries),
    });

    Ok(DurableMigrationSet {
        migrations,
        manifest: serde_json::to_string_pretty(&manifest)
            .context("serialise durable schema manifest")?,
        applicable_table_count: rendered.applicable_table_count,
    })
}

/// Lines each table already has from the released migrations: the whole block
/// of the migration that created it, then whatever released deltas appended.
fn covered_lines(released: &[ReleasedMigration]) -> Result<BTreeMap<String, Vec<String>>> {
    let mut covered: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for migration in released {
        let body = migration
            .sql
            .split_once("\n\n")
            .map(|(_, body)| body)
            .unwrap_or_default();
        let mut current: Option<(String, bool)> = None;
        for line in body.lines().filter(|line| !line.is_empty()) {
            if let Some(table) = line.strip_prefix(TABLE_HEADER) {
                if covered.insert(table.to_string(), Vec::new()).is_some() {
                    bail!(
                        "released migration {} recreates table '{table}'",
                        migration.version
                    );
                }
                current = Some((table.to_string(), true));
            } else if let Some(table) = line.strip_prefix(DELTA_HEADER) {
                if !covered.contains_key(table) {
                    bail!(
                        "released migration {} extends unknown table '{table}'",
                        migration.version
                    );
                }
                current = Some((table.to_string(), false));
            } else if let Some((table, _)) = &current {
                covered
                    .get_mut(table)
                    .expect("current table was inserted above")
                    .push(line.to_string());
            } else {
                bail!(
                    "released migration {} has SQL outside a table block",
                    migration.version
                );
            }
        }
    }
    Ok(covered)
}

fn is_index_line(line: &str) -> bool {
    line.starts_with("CREATE INDEX IF NOT EXISTS ")
        || line.starts_with("CREATE UNIQUE INDEX IF NOT EXISTS ")
}

/// The follow-up body for what `current` adds over `covered`, or an empty
/// string when nothing is new.  Tables are processed in name order.
///
/// A follow-up can only express new tables and new indexes.  Any other change
/// to an existing table would be a silent no-op under `CREATE TABLE IF NOT
/// EXISTS`, so it fails generation and needs an authored migration.
fn pending_delta_body(
    covered: &BTreeMap<String, Vec<String>>,
    current: &BTreeMap<String, String>,
) -> Result<String> {
    if let Some(table) = covered.keys().find(|table| !current.contains_key(*table)) {
        bail!(
            "released durable table '{table}' is no longer generated; removing or \
             retiring a released table needs an authored migration"
        );
    }
    let mut body = String::new();
    for (table, block) in current {
        let Some(covered_lines) = covered.get(table) else {
            body.push_str(block);
            continue;
        };
        let now: Vec<&str> = block
            .lines()
            .filter(|line| !line.is_empty() && !line.starts_with(TABLE_HEADER))
            .collect();
        let (now_indexes, now_rest): (Vec<&str>, Vec<&str>) =
            now.iter().partition(|line| is_index_line(line));
        let (covered_indexes, covered_rest): (Vec<&str>, Vec<&str>) = covered_lines
            .iter()
            .map(String::as_str)
            .partition(|line| is_index_line(line));
        if now_rest != covered_rest {
            bail!(
                "released durable table '{table}' changed beyond new indexes (columns, \
                 keys, constraints or partitioning); author an explicit migration"
            );
        }
        let mut remaining: BTreeMap<&str, usize> = BTreeMap::new();
        for line in &covered_indexes {
            *remaining.entry(line).or_default() += 1;
        }
        let mut added = Vec::new();
        for line in &now_indexes {
            match remaining.get_mut(line) {
                Some(count) if *count > 0 => *count -= 1,
                _ => added.push(*line),
            }
        }
        if let Some((line, _)) = remaining.iter().find(|(_, count)| **count > 0) {
            bail!("released durable table '{table}' lost index statement: {line}");
        }
        if !added.is_empty() {
            body.push_str(&format!("{DELTA_HEADER}{table}\n"));
            for line in added {
                body.push_str(line);
                body.push('\n');
            }
        }
    }
    Ok(body)
}

fn storage_policies(storage_policy_manifest: &Value) -> Result<BTreeMap<String, Value>> {
    if storage_policy_manifest["version"] != 1 {
        bail!("storage policy manifest version must be 1");
    }
    let policies = storage_policy_manifest["policies"]
        .as_array()
        .context("storage policy manifest: missing 'policies' array")?;
    let mut result = BTreeMap::new();
    for (index, policy) in policies.iter().enumerate() {
        let table = policy["table"]
            .as_str()
            .with_context(|| format!("storage policies[{index}].table is not a string"))?;
        if table.is_empty() {
            bail!("storage policies[{index}].table must not be empty");
        }
        if result.insert(table.to_string(), policy.clone()).is_some() {
            bail!("storage policy manifest has duplicate table '{table}'");
        }
    }
    Ok(result)
}

fn policy_projection_mode(policy: &Value) -> Result<&str> {
    policy["projection_mode"]
        .as_str()
        .context("storage policy is missing projection_mode")
}

fn policy_access_path(policy: &Value) -> Result<&str> {
    policy["postgres_access_path"]
        .as_str()
        .context("storage policy is missing postgres_access_path")
}

pub(super) fn effective_access_path<'a>(table: &str, requested: &'a str) -> &'a str {
    // These C2 protocol relations already exist in deployed C3 databases as
    // non-partitioned tables. Repartitioning them requires a later
    // expand/backfill/verify/contract migration, not a startup rewrite.
    if matches!(table, "organization_commit" | "organization_row_change") {
        "organization_index"
    } else {
        requested
    }
}

fn validate_identifier(identifier: &str) -> Result<()> {
    if !identifier.bytes().enumerate().all(|(index, byte)| {
        byte.is_ascii_lowercase() || byte.is_ascii_digit() || (index > 0 && byte == b'_')
    }) {
        bail!("invalid PostgreSQL identifier '{identifier}' in generated schema");
    }
    Ok(())
}

fn quote(identifier: &str) -> String {
    format!("\"{}\"", identifier.replace('"', "\"\""))
}

fn index_name(table: &str, index: &crate::cold_tier::schema_ir::GeneratedIndex) -> String {
    let suffix = index
        .name
        .strip_prefix(&format!("{table}_"))
        .unwrap_or(index.name.as_str());
    format!("{table}_{suffix}")
}

fn emitted_index_name(
    table: &str,
    index: &crate::cold_tier::schema_ir::GeneratedIndex,
    partitioned: bool,
) -> String {
    let name = index_name(table, index);
    if partitioned
        && index.unique
        && !index
            .columns
            .iter()
            .any(|column| column == "organization_id")
    {
        // A C3 heap can already have the original unique index name with a
        // non-tenant key. Use a distinct C4 name so IF NOT EXISTS cannot mask
        // the required tenant-prefixed replacement during adoption.
        format!("{name}_tenant")
    } else {
        name
    }
}

fn tenant_leading_index(
    schema: &GeneratedTableSchema,
) -> Option<&crate::cold_tier::schema_ir::GeneratedIndex> {
    schema
        .indexes
        .iter()
        .find(|index| index.columns.first().map(String::as_str) == Some("organization_id"))
}

fn emitted_index_columns(
    index: &crate::cold_tier::schema_ir::GeneratedIndex,
    partitioned: bool,
) -> Vec<String> {
    if partitioned
        && index.unique
        && !index
            .columns
            .iter()
            .any(|column| column == "organization_id")
    {
        let mut columns = Vec::with_capacity(index.columns.len() + 1);
        columns.push("organization_id".to_string());
        columns.extend(index.columns.iter().cloned());
        columns
    } else {
        index.columns.clone()
    }
}

fn render_table_sql(
    schema: &GeneratedTableSchema,
    policy: &Value,
    applicable: bool,
) -> Result<String> {
    let table = &schema.sql_name;
    let access_path = effective_access_path(table, policy_access_path(policy)?);
    let mut out = String::new();
    if !applicable {
        return Ok(out);
    }
    if schema.columns.is_empty() {
        bail!("durable table '{table}' has no columns");
    }
    out.push_str(&format!("-- Durable projection: {table}\n"));
    out.push_str(&format!("CREATE TABLE IF NOT EXISTS {} (\n", quote(table)));

    for column in &schema.columns {
        out.push_str(&format!(
            "    {} {}{},\n",
            quote(&column.sql_name),
            durable_pg_type(table, &column.sql_name, &column.ty),
            if column.nullable { "" } else { " NOT NULL" },
        ));
    }
    let pk_columns = if access_path == "organization_partition"
        && schema.organization_column().is_some()
        && schema.primary_key.column_name != "organization_id"
    {
        format!(
            "{}, {}",
            quote("organization_id"),
            quote(&schema.primary_key.column_name)
        )
    } else {
        quote(&schema.primary_key.column_name)
    };
    match table.as_str() {
        "organization_commit" => out.push_str(&format!(
            "    CONSTRAINT {} PRIMARY KEY ({pk_columns}),\n    CONSTRAINT {} UNIQUE ({}, {})\n",
            quote(&format!("{table}_pkey")),
            quote("organization_commit_org_sequence_key"),
            quote("organization_id"),
            quote("sequence"),
        )),
        "organization_row_change" => out.push_str(&format!(
            "    CONSTRAINT {} PRIMARY KEY ({pk_columns}),\n    CONSTRAINT {} FOREIGN KEY ({}, {}) REFERENCES {} ({}, {}),\n    CONSTRAINT {} UNIQUE ({}, {}, {}),\n    CONSTRAINT {} CHECK ({} IN ('upsert', 'delete')),\n    CONSTRAINT {} CHECK (({} = 'upsert' AND {} IS NOT NULL) OR ({} = 'delete' AND {} IS NULL))\n",
            quote(&format!("{table}_pkey")),
            quote("organization_row_change_commit_fk"),
            quote("organization_id"),
            quote("commit_sequence"),
            quote("organization_commit"),
            quote("organization_id"),
            quote("sequence"),
            quote("organization_row_change_commit_ordinal_key"),
            quote("organization_id"),
            quote("commit_sequence"),
            quote("ordinal"),
            quote("organization_row_change_kind_check"),
            quote("change_kind"),
            quote("organization_row_change_payload_check"),
            quote("change_kind"),
            quote("row_json"),
            quote("change_kind"),
            quote("row_json"),
        )),
        _ => out.push_str(&format!(
            "    CONSTRAINT {} PRIMARY KEY ({pk_columns})\n",
            quote(&format!("{table}_pkey"))
        )),
    }
    out.push(')');
    if access_path == "organization_partition" {
        if schema.organization_column().is_none() {
            bail!("organization_partition table '{table}' lacks organization_id");
        }
        out.push_str(&format!(
            " PARTITION BY HASH ({})",
            quote("organization_id")
        ));
    }
    out.push_str(";\n");

    if access_path == "organization_partition" {
        for remainder in 0..PARTITION_MODULUS {
            out.push_str(&format!(
                "DO $lumiere$\nBEGIN\n    IF EXISTS (SELECT 1 FROM pg_partitioned_table WHERE partrelid = to_regclass('{}')) THEN\n        CREATE TABLE IF NOT EXISTS {} PARTITION OF {} FOR VALUES WITH (MODULUS {PARTITION_MODULUS}, REMAINDER {remainder});\n    END IF;\nEND\n$lumiere$;\n",
                table,
                quote(&format!("{table}_p{remainder:02}")),
                quote(table),
            ));
        }
        // A C3 deployment may already own this relation as an ordinary heap
        // with a primary key on the row id alone.  The composite unique index
        // is valid for both that legacy layout and a fresh partitioned parent,
        // so projection upserts can use one tenant-safe conflict target during
        // the expand/backfill transition.
        out.push_str(&format!(
            "CREATE UNIQUE INDEX IF NOT EXISTS {} ON {} ({}, {});\n",
            quote(&format!("{table}_tenant_identity_key")),
            quote(table),
            quote("organization_id"),
            quote(&schema.primary_key.column_name),
        ));
    }

    let mut emitted_index_signatures = BTreeSet::new();
    for index in &schema.indexes {
        if index.columns.is_empty() {
            continue;
        }
        let name = emitted_index_name(table, index, access_path == "organization_partition");
        let effective_columns =
            emitted_index_columns(index, access_path == "organization_partition");
        let signature = (index.unique, effective_columns.clone());
        if !emitted_index_signatures.insert(signature) {
            continue;
        }
        let columns = effective_columns
            .iter()
            .map(|column| quote(column))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "CREATE {}INDEX IF NOT EXISTS {} ON {} ({columns});\n",
            if index.unique { "UNIQUE " } else { "" },
            quote(&name),
            quote(table),
        ));
    }

    let organization_owned = policy["organization_column"].as_str() == Some("organization_id");
    if organization_owned
        && schema.primary_key.column_name != "organization_id"
        && tenant_leading_index(schema).is_none()
    {
        out.push_str(&format!(
            "CREATE INDEX IF NOT EXISTS {} ON {} ({});\n",
            quote(&format!("{table}_organization_id")),
            quote(table),
            quote("organization_id")
        ));
    }
    Ok(out)
}

fn table_manifest_entry(
    schema: &GeneratedTableSchema,
    policy: &Value,
    applicable: bool,
    table_checksum: &str,
) -> Result<Value> {
    let requested_access_path = policy_access_path(policy)?;
    let access_path = effective_access_path(&schema.sql_name, requested_access_path);
    let tenant_index = tenant_leading_index(schema).map(|index| {
        serde_json::json!({
            "name": index_name(&schema.sql_name, index),
            "columns": index.columns,
            "unique": index.unique,
            "source": "schema_ir",
        })
    });
    let partitioned = access_path == "organization_partition";
    let indexes = schema
        .indexes
        .iter()
        .map(|index| {
            serde_json::json!({
                "name": emitted_index_name(&schema.sql_name, index, partitioned),
                "columns": emitted_index_columns(index, partitioned),
                "unique": index.unique,
            })
        })
        .collect::<Vec<_>>();
    Ok(serde_json::json!({
        "applicable": applicable,
        "module": policy["module"],
        "projection_mode": policy_projection_mode(policy)?,
        "postgres_access_path": access_path,
        "requested_postgres_access_path": requested_access_path,
        "layout_compatibility": if access_path != requested_access_path {
            "preserve_pre_c4_layout_until_expand_backfill_migration"
        } else {
            "native"
        },
        "organization_ownership": policy["organization_ownership"],
        "organization_column": policy["organization_column"],
        "primary_key": {
            "column": schema.primary_key.column_name,
            "rust_type": format!("{:?}", schema.primary_key.ty),
        },
        "columns": schema.columns.iter().map(|column| serde_json::json!({
            "name": column.sql_name,
            "rust_type": format!("{:?}", column.ty),
            "pg_type": durable_pg_type(&schema.sql_name, &column.sql_name, &column.ty),
            "nullable": column.nullable,
        })).collect::<Vec<_>>(),
        "indexes": indexes,
        "tenant_leading_index": tenant_index,
        "partition": if access_path == "organization_partition" {
            serde_json::json!({ "kind": "hash", "column": "organization_id", "modulus": PARTITION_MODULUS })
        } else {
            Value::Null
        },
        "schema_checksum": table_checksum,
    }))
}

fn checksum(input: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(input.as_bytes());
    format!("sha256:{}", hex::encode(hasher.finalize()))
}

