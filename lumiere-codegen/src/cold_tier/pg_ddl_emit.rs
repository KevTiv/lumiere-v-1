//! PG DDL generator.
//!
//! Consumes the stable Lumiere schema IR and emits `cold_{table}.sql` DDL
//! files for each archive-candidate table listed in `archive-candidates.json`.
//!
//! ## Type mapping
//!
//! | SpacetimeDB / Rust | Postgres DDL |
//! |--------------------|--------------|
//! | `U64`              | `NUMERIC(20,0)` — full unsigned range without sign loss |
//! | `U32`, `U16`, `U8` | `BIGINT` |
//! | `I64`              | `BIGINT` |
//! | `I32`, `I16`, `I8` | `INTEGER` |
//! | `F64`              | `DOUBLE PRECISION` |
//! | `F32`              | `REAL` |
//! | `Bool`             | `BOOLEAN` |
//! | `String`           | `TEXT` |
//! | `Timestamp`        | `BIGINT` (signed µs since Unix epoch) |
//! | `Identity`         | `BYTEA` (32-byte opaque identifier) |
//! | `Vec<T>`           | `JSONB` (encoded as a JSON array) |
//! | `Enum(_)`          | `TEXT` (canonical variant name) |
//! | `Struct(_)`        | `JSONB` (encoded as a JSON object) |
//!
//! ## Extra columns added to every cold table
//!
//! Every `cold_*` table receives two additional columns that are not present in
//! the source SpacetimeDB table:
//!
//! - `archived_at TIMESTAMPTZ NOT NULL DEFAULT now()` — wall-clock timestamp of
//!   the archival transfer.
//! - `payload_checksum TEXT NOT NULL` — hex-encoded SHA-256 of the canonical
//!   serialised payload, used by the finalize reducer to verify the archived
//!   copy before deleting the STDB row.

use anyhow::Result;

use crate::cold_tier::codec_emit::pg_type_for;
use crate::cold_tier::schema_ir::{GeneratedTableSchema, LumiereSchemaManifest};

/// Emit the append-only C2 commit stream and projection watermark tables.
///
/// These tables are shared projection infrastructure rather than business
/// tables, so their DDL is generated here alongside the per-table projection
/// DDL and applied by the API server at startup.
pub fn emit_commit_stream_ddl() -> [(&'static str, String); 5] {
    [
        (
            "organization_commit.sql",
            r#"-- Auto-generated by lumiere-codegen. Do not edit.
CREATE TABLE IF NOT EXISTS organization_commit (
    id TEXT NOT NULL,
    organization_id NUMERIC(20,0) NOT NULL,
    sequence NUMERIC(20,0) NOT NULL,
    operation_id TEXT NOT NULL,
    correlation_id TEXT NOT NULL,
    change_schema_version BIGINT NOT NULL,
    contract_version TEXT NOT NULL,
    occurred_at BIGINT NOT NULL,
    actor_identity BYTEA NOT NULL,
    row_change_count BIGINT NOT NULL,
    checksum TEXT NOT NULL,
    CONSTRAINT organization_commit_pkey PRIMARY KEY (id),
    CONSTRAINT organization_commit_org_sequence_key UNIQUE (organization_id, sequence)
);

CREATE INDEX IF NOT EXISTS organization_commit_org_sequence
    ON organization_commit (organization_id, sequence);
"#
            .to_string(),
        ),
        (
            "organization_row_change.sql",
            r#"-- Auto-generated by lumiere-codegen. Do not edit.
CREATE TABLE IF NOT EXISTS organization_row_change (
    id TEXT NOT NULL,
    organization_id NUMERIC(20,0) NOT NULL,
    commit_sequence NUMERIC(20,0) NOT NULL,
    ordinal BIGINT NOT NULL,
    table_name TEXT NOT NULL,
    row_identity_json JSONB NOT NULL,
    change_kind TEXT NOT NULL,
    row_json JSONB,
    checksum TEXT NOT NULL,
    CONSTRAINT organization_row_change_pkey PRIMARY KEY (id),
    CONSTRAINT organization_row_change_commit_fk
        FOREIGN KEY (organization_id, commit_sequence)
        REFERENCES organization_commit (organization_id, sequence),
    CONSTRAINT organization_row_change_commit_ordinal_key
        UNIQUE (organization_id, commit_sequence, ordinal),
    CONSTRAINT organization_row_change_kind_check
        CHECK (change_kind IN ('upsert', 'delete')),
    CONSTRAINT organization_row_change_payload_check
        CHECK ((change_kind = 'upsert' AND row_json IS NOT NULL)
            OR (change_kind = 'delete' AND row_json IS NULL))
);

CREATE INDEX IF NOT EXISTS organization_row_change_commit_order
    ON organization_row_change (organization_id, commit_sequence, ordinal);
"#
            .to_string(),
        ),
        (
            "organization_projection_watermark.sql",
            r#"-- Auto-generated by lumiere-codegen. Do not edit.
CREATE TABLE IF NOT EXISTS organization_projection_watermark (
    organization_id NUMERIC(20,0) NOT NULL,
    applied_sequence NUMERIC(20,0) NOT NULL,
    commit_id TEXT NOT NULL,
    commit_checksum TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT organization_projection_watermark_pkey PRIMARY KEY (organization_id)
);
"#
            .to_string(),
        ),
        (
            "organization_projection_quarantine.sql",
            r#"-- Auto-generated by lumiere-codegen. Do not edit.
CREATE TABLE IF NOT EXISTS organization_projection_quarantine (
    organization_id NUMERIC(20,0) NOT NULL,
    sequence NUMERIC(20,0) NOT NULL,
    failure_kind TEXT NOT NULL,
    error_message TEXT NOT NULL,
    attempts BIGINT NOT NULL DEFAULT 1,
    first_observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT organization_projection_quarantine_pkey
        PRIMARY KEY (organization_id, sequence),
    CONSTRAINT organization_projection_quarantine_failure_kind_length
        CHECK (octet_length(failure_kind) <= 128),
    CONSTRAINT organization_projection_quarantine_error_message_length
        CHECK (octet_length(error_message) <= 4096)
);

CREATE INDEX IF NOT EXISTS organization_projection_quarantine_last_observed
    ON organization_projection_quarantine (last_observed_at);
"#
            .to_string(),
        ),
        (
            "organization_projection_status.sql",
            r#"-- Auto-generated by lumiere-codegen. Do not edit.
CREATE TABLE IF NOT EXISTS organization_projection_status (
    organization_id NUMERIC(20,0) NOT NULL,
    stdb_head_sequence NUMERIC(20,0) NOT NULL,
    durable_sequence NUMERIC(20,0) NOT NULL,
    backlog_commits NUMERIC(20,0) NOT NULL,
    oldest_unprojected_at BIGINT,
    last_error TEXT,
    quarantined_sequence NUMERIC(20,0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT organization_projection_status_pkey PRIMARY KEY (organization_id),
    CONSTRAINT organization_projection_status_error_message_length
        CHECK (last_error IS NULL OR octet_length(last_error) <= 4096)
);

CREATE INDEX IF NOT EXISTS organization_projection_status_backlog
    ON organization_projection_status (backlog_commits, updated_at);
"#
            .to_string(),
        ),
    ]
}

/// Config for one archive candidate (from `archive-candidates.json`).
#[derive(Debug)]
pub struct ArchiveCandidateConfig<'a> {
    /// Source STDB table name, e.g. `"audit_log"`.
    pub table: &'a str,
    /// Target PG cold table name, e.g. `"cold_audit_log"`.
    pub cold_table: &'a str,
}

/// Emit PG DDL for the cold table corresponding to `config.table`.
///
/// Returns the SQL text.  The caller is responsible for writing it to the
/// appropriate output path.
pub fn emit_cold_table_ddl(
    manifest: &LumiereSchemaManifest,
    config: &ArchiveCandidateConfig<'_>,
) -> Result<String> {
    let schema = manifest
        .tables
        .iter()
        .find(|t| t.sql_name == config.table)
        .ok_or_else(|| {
            anyhow::anyhow!(
                "table '{}' not found in schema manifest — \
                 run `make generate-stdb-rust-sdk` and `make codegen` first",
                config.table
            )
        })?;

    Ok(render_ddl(schema, config.cold_table))
}

fn render_ddl(schema: &GeneratedTableSchema, cold_table: &str) -> String {
    let mut out = String::new();

    out.push_str("-- Auto-generated by lumiere-codegen. Do not edit.\n");
    out.push_str(&format!(
        "-- Source table: {src}  →  Cold table: {cold}\n",
        src = schema.sql_name,
        cold = cold_table
    ));
    out.push('\n');

    // ── CREATE TABLE ────────────────────────────────────────────────────────
    out.push_str(&format!("CREATE TABLE IF NOT EXISTS {} (\n", cold_table));

    // Primary key first (always NUMERIC(20,0) since all STDB PKs are u64).
    out.push_str(&format!(
        "    {} {} NOT NULL,\n",
        schema.primary_key.column_name,
        pg_type_for(&schema.primary_key.ty)
    ));

    // Remaining columns in declaration order, skipping PK (already emitted).
    for col in &schema.columns {
        if col.name == schema.primary_key.column_name {
            continue;
        }
        out.push_str(&format!(
            "    {} {}{}",
            col.sql_name,
            pg_type_for(&col.ty),
            if col.nullable { "" } else { " NOT NULL" }
        ));
        out.push_str(",\n");
    }

    // Extra columns present on every cold table.
    out.push_str("    archived_at TIMESTAMPTZ NOT NULL DEFAULT now(),\n");
    out.push_str("    payload_checksum TEXT NOT NULL,\n");

    // Primary key constraint.
    out.push_str(&format!(
        "    CONSTRAINT {cold_table}_pkey PRIMARY KEY ({pk})\n",
        cold_table = cold_table,
        pk = schema.primary_key.column_name
    ));

    out.push_str(");\n");
    out.push('\n');

    // ── UPSERT INDEX (version-aware, needed by the version-aware UPSERT) ────
    // No additional unique index needed: the PK constraint handles it.

    // ── Non-PK indexes ───────────────────────────────────────────────────────
    for index in &schema.indexes {
        let cols = index.columns.join(", ");
        let unique = if index.unique { "UNIQUE " } else { "" };
        out.push_str(&format!(
            "CREATE {unique}INDEX IF NOT EXISTS {idx_name} ON {cold_table} ({cols});\n",
            unique = unique,
            idx_name = format!(
                "{}_{}",
                cold_table,
                index
                    .name
                    .trim_start_matches(&format!("{}_", schema.sql_name))
            ),
            cold_table = cold_table,
            cols = cols
        ));
    }

    // Always add an index on `archived_at` for operational queries.
    out.push_str(&format!(
        "CREATE INDEX IF NOT EXISTS {cold_table}_archived_at ON {cold_table} (archived_at);\n",
        cold_table = cold_table
    ));

    out
}

