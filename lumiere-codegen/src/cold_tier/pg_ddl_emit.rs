#[cfg(test)]
mod tests {
    use super::*;
    use crate::cold_tier::schema_ir::*;

    fn audit_log_schema() -> GeneratedTableSchema {
        GeneratedTableSchema {
            rust_name: "AuditLog".into(),
            sql_name: "audit_log".into(),
            primary_key: GeneratedPrimaryKey {
                column_name: "id".into(),
                ty: GeneratedType::U64,
            },
            columns: vec![
                GeneratedColumn {
                    name: "id".into(),
                    sql_name: "id".into(),
                    ty: GeneratedType::U64,
                    nullable: false,
                },
                GeneratedColumn {
                    name: "organization_id".into(),
                    sql_name: "organization_id".into(),
                    ty: GeneratedType::U64,
                    nullable: false,
                },
                GeneratedColumn {
                    name: "company_id".into(),
                    sql_name: "company_id".into(),
                    ty: GeneratedType::U64,
                    nullable: true,
                },
                GeneratedColumn {
                    name: "table_name".into(),
                    sql_name: "table_name".into(),
                    ty: GeneratedType::String,
                    nullable: false,
                },
                GeneratedColumn {
                    name: "changed_fields".into(),
                    sql_name: "changed_fields".into(),
                    ty: GeneratedType::Vec(Box::new(GeneratedType::String)),
                    nullable: false,
                },
                GeneratedColumn {
                    name: "user_identity".into(),
                    sql_name: "user_identity".into(),
                    ty: GeneratedType::Identity,
                    nullable: false,
                },
                GeneratedColumn {
                    name: "timestamp".into(),
                    sql_name: "timestamp".into(),
                    ty: GeneratedType::Timestamp,
                    nullable: false,
                },
            ],
            indexes: vec![GeneratedIndex {
                name: "audit_log_organization_id".into(),
                columns: vec!["organization_id".into()],
                unique: false,
            }],
        }
    }

    #[test]
    fn ddl_contains_expected_fragments() {
        let schema = audit_log_schema();
        let ddl = render_ddl(&schema, "cold_audit_log");

        assert!(
            ddl.contains("CREATE TABLE IF NOT EXISTS cold_audit_log"),
            "missing CREATE TABLE"
        );
        assert!(
            ddl.contains("id NUMERIC(20,0) NOT NULL"),
            "missing PK column"
        );
        assert!(
            ddl.contains("organization_id NUMERIC(20,0) NOT NULL"),
            "missing org_id NOT NULL"
        );
        assert!(
            ddl.contains("company_id NUMERIC(20,0),"),
            "missing nullable company_id"
        );
        assert!(
            ddl.contains("changed_fields JSONB NOT NULL"),
            "missing JSONB column"
        );
        assert!(
            ddl.contains("user_identity BYTEA NOT NULL"),
            "missing BYTEA column"
        );
        assert!(
            ddl.contains("timestamp BIGINT NOT NULL"),
            "missing BIGINT timestamp"
        );
        assert!(
            ddl.contains("archived_at TIMESTAMPTZ NOT NULL DEFAULT now()"),
            "missing archived_at"
        );
        assert!(
            ddl.contains("payload_checksum TEXT NOT NULL"),
            "missing payload_checksum"
        );
        assert!(ddl.contains("PRIMARY KEY (id)"), "missing PRIMARY KEY");
    }

    #[test]
    fn commit_stream_ddl_has_ordering_and_tombstone_constraints() {
        let ddl = emit_commit_stream_ddl();
        assert!(ddl[0].1.contains("UNIQUE (organization_id, sequence)"));
        assert!(ddl[1]
            .1
            .contains("UNIQUE (organization_id, commit_sequence, ordinal)"));
        assert!(ddl[1]
            .1
            .contains("FOREIGN KEY (organization_id, commit_sequence)"));
        assert!(ddl[1].1.contains("change_kind IN ('upsert', 'delete')"));
        assert!(ddl[3].1.contains("organization_projection_quarantine"));
        assert!(ddl[3].1.contains("octet_length(error_message) <= 4096"));
        assert!(ddl[4].1.contains("organization_projection_status"));
        assert!(ddl[4].1.contains("quarantined_sequence"));
        assert!(ddl[4].1.contains("octet_length(last_error) <= 4096"));
        assert!(ddl[1]
            .1
            .contains("change_kind = 'delete' AND row_json IS NULL"));
        assert!(ddl[2].1.contains("PRIMARY KEY (organization_id)"));
    }

    #[test]
    fn type_mapping_u64_is_numeric() {
        assert_eq!(pg_type_for(&GeneratedType::U64), "NUMERIC(20,0)");
    }

    #[test]
    fn type_mapping_identity_is_bytea() {
        assert_eq!(pg_type_for(&GeneratedType::Identity), "BYTEA");
    }

    #[test]
    fn emit_requires_known_table() {
        let manifest = LumiereSchemaManifest {
            version: 1,
            tables: vec![],
            enum_types: vec![],
        };
        let cfg = ArchiveCandidateConfig {
            table: "audit_log",
            cold_table: "cold_audit_log",
        };
        assert!(emit_cold_table_ddl(&manifest, &cfg).is_err());
    }
}
