//! Emit the closed SpacetimeDB dispatch used by organization reconstruction.
//!
//! The dispatch is generated from the reviewed reconstruction manifest and
//! the module source that declared each table. This keeps table names, row
//! types, ownership columns, primary keys, and restore order out of runtime
//! caller control.

use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Deserialize)]
struct Manifest {
    version: u64,
    tables: Vec<Table>,
}

#[derive(Deserialize)]
struct Table {
    table: String,
    rust_type: String,
    stdb_table_accessor: String,
    organization_column: String,
    primary_key: String,
    restore_order: u32,
}

struct SourceTable {
    rust_path: String,
    rust_type: String,
    accessor: String,
}

struct SourceFile {
    path: PathBuf,
    compact: String,
}

/// Generate a Rust match with one arm for every reviewed reconstruction table.
pub fn emit_reconstruction_apply(manifest_json: &str, spacetimedb_src: &Path) -> Result<String> {
    let manifest: Manifest =
        serde_json::from_str(manifest_json).context("parse reconstruction manifest")?;
    if manifest.version != 1 || manifest.tables.is_empty() {
        bail!("reconstruction apply requires a non-empty version 1 manifest");
    }

    let source_files = rust_source_files(spacetimedb_src)?;
    let mut orders = BTreeMap::new();
    let mut arms = String::new();
    for table in &manifest.tables {
        if table.organization_column != "organization_id" {
            bail!(
                "reconstruction apply only supports direct organization_id ownership: {}",
                table.table
            );
        }
        if table.table != table.stdb_table_accessor {
            bail!("table/accessor mismatch for {}", table.table);
        }
        if orders.insert(table.restore_order, &table.table).is_some() {
            bail!(
                "duplicate reconstruction restore order {}",
                table.restore_order
            );
        }
        let source = locate_table_source(table, spacetimedb_src, &source_files)?;
        arms.push_str(&emit_arm(table, &source));
    }

    Ok(format!(
        r#"// @generated by lumiere-codegen from the canonical reconstruction manifest.
// Do not edit by hand.

use spacetimedb::{{ReducerContext, Table}};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum GeneratedApplyOutcome {{
    Inserted,
    AlreadyPresent,
}}

pub(crate) fn generated_restore_order(table: &str) -> Option<u32> {{
    match table {{
{orders}        _ => None,
    }}
}}

pub(crate) const GENERATED_FINAL_RESTORE_ORDER: u32 = {final_restore_order};

pub(crate) fn apply_generated_reconstruction_row(
    ctx: &ReducerContext,
    organization_id: u64,
    table_name: &str,
    row_json: &str,
) -> Result<GeneratedApplyOutcome, String> {{
    match table_name {{
{arms}        _ => Err("table is not in the generated reconstruction allowlist".to_string()),
    }}
}}
"#,
        orders = manifest
            .tables
            .iter()
            .map(|table| format!(
                "        {:?} => Some({}),\n",
                table.table, table.restore_order
            ))
            .collect::<String>(),
        arms = arms,
        final_restore_order = manifest
            .tables
            .iter()
            .map(|table| table.restore_order)
            .max()
            .unwrap_or(0),
    ))
}

fn emit_arm(table: &Table, source: &SourceTable) -> String {
    format!(
        r#"        {table_name:?} => {{
            use crate::{rust_path}::{{{accessor} as _, {rust_type}}};
            let spacetimedb_sats::serde::SerdeWrapper(row) =
                serde_json::from_str::<spacetimedb_sats::serde::SerdeWrapper<{rust_type}>>(row_json)
                    .map_err(|error| format!("invalid canonical row JSON for {table_name}: {{error}}"))?;
            if row.{organization_column} != organization_id {{
                return Err("reconstruction row belongs to a different organization".to_string());
            }}
            let rows = ctx.db.{accessor}();
            if let Some(existing) = rows.{primary_key}().find(&row.{primary_key}) {{
                let existing_json = serde_json::to_value(
                    spacetimedb_sats::serde::SerdeWrapper::from_ref(&existing),
                )
                .map_err(|error| format!("serialize existing {table_name} row: {{error}}"))?;
                let incoming_json = serde_json::to_value(
                    spacetimedb_sats::serde::SerdeWrapper::from_ref(&row),
                )
                .map_err(|error| format!("serialize incoming {table_name} row: {{error}}"))?;
                if existing_json == incoming_json {{
                    Ok(GeneratedApplyOutcome::AlreadyPresent)
                }} else {{
                    Err("reconstruction primary-key conflict with different row data".to_string())
                }}
            }} else {{
                rows.insert(row);
                Ok(GeneratedApplyOutcome::Inserted)
            }}
        }},
"#,
        table_name = table.table,
        rust_path = source.rust_path,
        accessor = source.accessor,
        rust_type = source.rust_type,
        organization_column = table.organization_column,
        primary_key = table.primary_key,
    )
}

fn locate_table_source(table: &Table, root: &Path, files: &[SourceFile]) -> Result<SourceTable> {
    let mut matches = Vec::new();
    for file in files {
        for (accessor, rust_type) in declared_tables(&file.compact) {
            if accessor == table.stdb_table_accessor
                || canonical_name(&accessor) == canonical_name(&table.table)
                || canonical_name(&rust_type) == canonical_name(&table.rust_type)
            {
                matches.push((&file.path, accessor, rust_type));
            }
        }
    }
    if matches.len() != 1 {
        bail!(
            "expected exactly one source declaration for table {} / type {}, found {}",
            table.table,
            table.rust_type,
            matches.len()
        );
    }
    Ok(SourceTable {
        rust_path: module_path(root, matches[0].0)?,
        accessor: matches[0].1.clone(),
        rust_type: matches[0].2.clone(),
    })
}

fn declared_tables(source: &str) -> Vec<(String, String)> {
    const TABLE_MACROS: [&str; 2] = ["#[spacetimedb::table(", "#[table("];
    let mut declarations = Vec::new();
    let mut remaining = source;
    while let Some((macro_at, macro_name)) = TABLE_MACROS
        .iter()
        .filter_map(|name| remaining.find(name).map(|at| (at, *name)))
        .min_by_key(|(at, _)| *at)
    {
        let after_macro = &remaining[macro_at + macro_name.len()..];
        let Some(rust_type) = struct_name_after(after_macro) else {
            break;
        };
        let Some(struct_at) = after_macro.find(&rust_type) else {
            break;
        };
        let attribute = &after_macro[..struct_at];
        if let Some(accessor_at) = attribute.find("accessor=") {
            let value = &attribute[accessor_at + "accessor=".len()..];
            let end = value
                .find(|char: char| !(char.is_ascii_alphanumeric() || char == '_'))
                .unwrap_or(value.len());
            if end > 0 {
                declarations.push((value[..end].to_string(), rust_type));
            }
        }
        remaining = &after_macro[struct_at + 1..];
    }
    declarations
}

fn canonical_name(value: &str) -> String {
    value
        .chars()
        .filter(|char| *char != '_')
        .flat_map(char::to_lowercase)
        .collect()
}

fn struct_name_after(source: &str) -> Option<String> {
    let candidates = ["pubstruct", "pub(crate)struct"];
    let (at, prefix) = candidates
        .iter()
        .filter_map(|prefix| source.find(prefix).map(|at| (at, *prefix)))
        .min_by_key(|(at, _)| *at)?;
    let name = &source[at + prefix.len()..];
    let end = name.find(|char: char| !(char.is_ascii_alphanumeric() || char == '_'))?;
    (end > 0).then(|| name[..end].to_string())
}

fn rust_source_files(root: &Path) -> Result<Vec<SourceFile>> {
    fn visit(dir: &Path, files: &mut Vec<PathBuf>) -> Result<()> {
        for entry in fs::read_dir(dir).with_context(|| format!("read {}", dir.display()))? {
            let path = entry?.path();
            if path.is_dir() {
                visit(&path, files)?;
            } else if path.extension().and_then(|value| value.to_str()) == Some("rs") {
                files.push(path);
            }
        }
        Ok(())
    }
    let mut files = Vec::new();
    visit(root, &mut files)?;
    files.sort();
    files
        .into_iter()
        .map(|path| {
            let source = fs::read_to_string(&path)
                .with_context(|| format!("read SpacetimeDB source {}", path.display()))?;
            Ok(SourceFile {
                path,
                compact: source
                    .chars()
                    .filter(|char| !char.is_whitespace())
                    .collect(),
            })
        })
        .collect()
}

fn module_path(root: &Path, file: &Path) -> Result<String> {
    let relative = file
        .strip_prefix(root)
        .with_context(|| format!("{} is outside {}", file.display(), root.display()))?;
    let mut parts = relative
        .components()
        .map(|part| part.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>();
    let file_name = parts.pop().context("Rust source path has no file name")?;
    let stem = file_name
        .strip_suffix(".rs")
        .context("Rust source does not end in .rs")?;
    if stem != "mod" && stem != "lib" {
        parts.push(stem.to_string());
    }
    if parts.is_empty() {
        bail!("table declarations in the crate root are not supported");
    }
    Ok(parts.join("::"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_closed_tenant_checked_idempotent_arm() {
        let root = std::env::temp_dir().join(format!(
            "lumiere-reconstruction-apply-{}",
            std::process::id()
        ));
        let module = root.join("sales");
        fs::create_dir_all(&module).unwrap();
        fs::write(
            module.join("orders.rs"),
            "#[spacetimedb::table(accessor = pos_order, public)]\npub struct PosOrder { pub id: u64, pub organization_id: u64 }",
        )
        .unwrap();
        let manifest = r#"{"version":1,"tables":[{"table":"pos_order","rust_type":"PosOrder","stdb_table_accessor":"pos_order","organization_column":"organization_id","primary_key":"id","restore_order":7}]}"#;
        let output = emit_reconstruction_apply(manifest, &root).unwrap();
        assert!(output.contains("use crate::sales::orders::{pos_order as _, PosOrder};"));
        assert!(output.contains("row.organization_id != organization_id"));
        assert!(output.contains("rows.id().find(&row.id)"));
        assert!(output.contains("\"pos_order\" => Some(7)"));
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn parses_acronym_table_declaration() {
        let source = "#[spacetimedb::table(accessor = iot_action, public, index(accessor = iot_action_by_org, btree(columns = [organization_id])))] pub struct IoTAction { pub id: u64 }";
        let compact: String = source
            .chars()
            .filter(|char| !char.is_whitespace())
            .collect();
        assert_eq!(
            declared_tables(&compact),
            vec![("iot_action".to_string(), "IoTAction".to_string())]
        );
    }
}
