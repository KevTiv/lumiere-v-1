//! PG codec manifest generator.
//!
//! Emits `crates/stdb-auth/assets/codec-manifest.json` describing the type
//! mapping from SpacetimeDB Rust types to Postgres bind/return types and the
//! reverse conversion to API JSON.  This keeps the drainer, finalize reducer,
//! and read-merge path from each independently hard-coding per-column logic.
//!
//! ## Output schema
//!
//! ```json
//! {
//!   "version": 1,
//!   "checksum_algo": "sha256",
//!   "canonical_serialization": "json_sorted_keys",
//!   "tables": {
//!     "audit_log": {
//!       "cold_table": "cold_audit_log",
//!       "columns": [
//!         {
//!           "name": "id",
//!           "stdb_type": "U64",
//!           "pg_type": "NUMERIC(20,0)",
//!           "nullable": false,
//!           "pg_bind": "to_sql_numeric",
//!           "pg_from": "from_sql_numeric_to_string",
//!           "api_json": "string"
//!         },
//!         ...
//!       ],
//!       "extra_columns": ["archived_at", "payload_checksum"]
//!     }
//!   }
//! }
//! ```
//!
//! The `pg_bind` and `pg_from` fields name convention functions that the
//! runtime codec (Phase 1) implements as a function table.

use anyhow::{Context, Result};
use serde_json::Value;

use crate::schema_ir::{GeneratedTableSchema, GeneratedType, LumiereSchemaManifest};

/// Build the codec manifest for all archive-candidate tables.
///
/// `candidates_json` is the raw `archive-candidates.json` text (same input as
/// the archive manifest).  Returns the pretty-printed JSON string.
pub fn emit_codec_manifest(
    candidates_json: &str,
    schema_manifest: &LumiereSchemaManifest,
) -> Result<String> {
    let config: Value =
        serde_json::from_str(candidates_json).context("parse archive-candidates.json")?;

    let candidates = config["candidates"]
        .as_array()
        .context("archive-candidates.json: missing 'candidates' array")?;

    let mut tables = serde_json::Map::new();

    for (i, cand) in candidates.iter().enumerate() {
        let table = cand["table"]
            .as_str()
            .with_context(|| format!("candidates[{i}].table is not a string"))?;
        let cold_table = cand["cold_table"]
            .as_str()
            .with_context(|| format!("candidates[{i}].cold_table is not a string"))?;

        let schema = schema_manifest
            .tables
            .iter()
            .find(|t| t.sql_name == table)
            .with_context(|| {
                format!("candidates[{i}]: table '{table}' not found in schema manifest")
            })?;

        let entry = build_table_entry(schema, cold_table);
        tables.insert(table.to_string(), entry);
    }

    let manifest = serde_json::json!({
        "version": 1,
        "_comment": "Auto-generated by lumiere-codegen. Do not edit.",
        "checksum_algo": "sha256",
        "canonical_serialization": "json_sorted_keys_no_whitespace",
        "tables": Value::Object(tables),
    });

    serde_json::to_string_pretty(&manifest).context("serialise codec manifest")
}

fn build_table_entry(schema: &GeneratedTableSchema, cold_table: &str) -> Value {
    let columns: Vec<Value> = schema
        .columns
        .iter()
        .map(|col| {
            serde_json::json!({
                "name": col.name,
                "stdb_type": format!("{:?}", col.ty),
                "pg_type": pg_type_for(&col.ty),
                "nullable": col.nullable,
                "pg_bind": pg_bind_fn(&col.ty),
                "pg_from": pg_from_fn(&col.ty),
                "api_json": api_json_repr(&col.ty),
            })
        })
        .collect();

    serde_json::json!({
        "cold_table": cold_table,
        "columns": columns,
        "extra_columns": ["archived_at", "payload_checksum"],
    })
}

/// Map a `GeneratedType` to the Postgres DDL type string (must match pg_ddl_emit.rs).
fn pg_type_for(ty: &GeneratedType) -> &'static str {
    match ty {
        GeneratedType::U64 => "NUMERIC(20,0)",
        GeneratedType::U8 | GeneratedType::U16 | GeneratedType::U32 => "BIGINT",
        GeneratedType::I64 => "BIGINT",
        GeneratedType::I8 | GeneratedType::I16 | GeneratedType::I32 => "INTEGER",
        GeneratedType::F64 => "DOUBLE PRECISION",
        GeneratedType::F32 => "REAL",
        GeneratedType::Bool => "BOOLEAN",
        GeneratedType::String => "TEXT",
        GeneratedType::Timestamp => "BIGINT",
        GeneratedType::Identity => "BYTEA",
        GeneratedType::Vec(_) | GeneratedType::Struct(_) => "JSONB",
        GeneratedType::Enum(_) => "TEXT",
    }
}

/// Name the convention function for binding a Rust value to a PG parameter.
fn pg_bind_fn(ty: &GeneratedType) -> &'static str {
    match ty {
        GeneratedType::U64 => "to_sql_numeric",
        GeneratedType::U8 | GeneratedType::U16 | GeneratedType::U32 => "to_sql_bigint_u",
        GeneratedType::I64 => "to_sql_bigint",
        GeneratedType::I8 | GeneratedType::I16 | GeneratedType::I32 => "to_sql_int",
        GeneratedType::F64 => "to_sql_f64",
        GeneratedType::F32 => "to_sql_f32",
        GeneratedType::Bool => "to_sql_bool",
        GeneratedType::String => "to_sql_text",
        GeneratedType::Timestamp => "to_sql_bigint",
        GeneratedType::Identity => "to_sql_bytea",
        GeneratedType::Vec(_) => "to_sql_jsonb",
        GeneratedType::Enum(_) => "to_sql_text",
        GeneratedType::Struct(_) => "to_sql_jsonb",
    }
}

/// Name the convention function for converting a PG return value to API JSON.
fn pg_from_fn(ty: &GeneratedType) -> &'static str {
    match ty {
        GeneratedType::U64 => "from_sql_numeric_to_string",
        GeneratedType::U8 | GeneratedType::U16 | GeneratedType::U32 => "from_sql_bigint_to_string",
        GeneratedType::I64 => "from_sql_bigint_to_string",
        GeneratedType::I8 | GeneratedType::I16 | GeneratedType::I32 => "from_sql_int_to_number",
        GeneratedType::F64 => "from_sql_f64_to_number",
        GeneratedType::F32 => "from_sql_f32_to_number",
        GeneratedType::Bool => "from_sql_bool",
        GeneratedType::String => "from_sql_text",
        GeneratedType::Timestamp => "from_sql_bigint_to_iso_string",
        GeneratedType::Identity => "from_sql_bytea_to_hex_string",
        GeneratedType::Vec(_) => "from_sql_jsonb_to_array",
        GeneratedType::Enum(_) => "from_sql_text",
        GeneratedType::Struct(_) => "from_sql_jsonb_to_object",
    }
}

/// How the type is represented in API JSON responses.
fn api_json_repr(ty: &GeneratedType) -> &'static str {
    match ty {
        GeneratedType::U64 => "string",
        GeneratedType::U8 | GeneratedType::U16 | GeneratedType::U32 => "string",
        GeneratedType::I64 => "string",
        GeneratedType::I8 | GeneratedType::I16 | GeneratedType::I32 => "number",
        GeneratedType::F64 | GeneratedType::F32 => "number",
        GeneratedType::Bool => "boolean",
        GeneratedType::String => "string",
        GeneratedType::Timestamp => "string",
        GeneratedType::Identity => "string",
        GeneratedType::Vec(_) => "array",
        GeneratedType::Enum(_) => "string",
        GeneratedType::Struct(_) => "object",
    }
}

