#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema_ir::*;

    fn audit_log_manifest() -> LumiereSchemaManifest {
        LumiereSchemaManifest {
            version: 1,
            tables: vec![GeneratedTableSchema {
                rust_name: "AuditLog".into(),
                sql_name: "audit_log".into(),
                primary_key: GeneratedPrimaryKey {
                    column_name: "id".into(),
                    ty: GeneratedType::U64,
                },
                columns: vec![
                    GeneratedColumn {
                        name: "id".into(),
                        sql_name: "id".into(),
                        ty: GeneratedType::U64,
                        nullable: false,
                    },
                    GeneratedColumn {
                        name: "organization_id".into(),
                        sql_name: "organization_id".into(),
                        ty: GeneratedType::U64,
                        nullable: false,
                    },
                    GeneratedColumn {
                        name: "user_identity".into(),
                        sql_name: "user_identity".into(),
                        ty: GeneratedType::Identity,
                        nullable: false,
                    },
                    GeneratedColumn {
                        name: "changed_fields".into(),
                        sql_name: "changed_fields".into(),
                        ty: GeneratedType::Vec(Box::new(GeneratedType::String)),
                        nullable: false,
                    },
                ],
                indexes: vec![],
            }],
            enum_types: vec![],
        }
    }

    fn candidates_json() -> String {
        serde_json::json!({
            "version": 1,
            "candidates": [{
                "table": "audit_log",
                "cold_table": "cold_audit_log",
                "mode": "append_only",
                "finalize_reducer": "finalize_audit_log_archive",
                "order_by": [{ "column": "id", "direction": "ASC" }]
            }]
        })
        .to_string()
    }

    #[test]
    fn emit_contains_expected_fields() {
        let manifest = audit_log_manifest();
        let candidates = candidates_json();
        let out = emit_codec_manifest(&candidates, &manifest).unwrap();
        let parsed: Value = serde_json::from_str(&out).unwrap();

        assert_eq!(parsed["version"], 1);
        assert_eq!(parsed["checksum_algo"], "sha256");
        assert_eq!(
            parsed["canonical_serialization"],
            "json_sorted_keys_no_whitespace"
        );

        let audit = &parsed["tables"]["audit_log"];
        assert_eq!(audit["cold_table"], "cold_audit_log");
        assert_eq!(audit["extra_columns"][0], "archived_at");
        assert_eq!(audit["extra_columns"][1], "payload_checksum");

        // Check the U64 → NUMERIC mapping.
        let id_col = &audit["columns"][0];
        assert_eq!(id_col["name"], "id");
        assert_eq!(id_col["pg_type"], "NUMERIC(20,0)");
        assert_eq!(id_col["pg_bind"], "to_sql_numeric");
        assert_eq!(id_col["pg_from"], "from_sql_numeric_to_string");
        assert_eq!(id_col["api_json"], "string");
    }

    #[test]
    fn emit_identity_maps_to_bytea() {
        let manifest = audit_log_manifest();
        let candidates = candidates_json();
        let out = emit_codec_manifest(&candidates, &manifest).unwrap();
        let parsed: Value = serde_json::from_str(&out).unwrap();

        let identity_col = parsed["tables"]["audit_log"]["columns"]
            .as_array()
            .unwrap()
            .iter()
            .find(|c| c["name"] == "user_identity")
            .unwrap();
        assert_eq!(identity_col["pg_type"], "BYTEA");
        assert_eq!(identity_col["pg_bind"], "to_sql_bytea");
        assert_eq!(identity_col["api_json"], "string");
    }

    #[test]
    fn emit_vec_maps_to_jsonb() {
        let manifest = audit_log_manifest();
        let candidates = candidates_json();
        let out = emit_codec_manifest(&candidates, &manifest).unwrap();
        let parsed: Value = serde_json::from_str(&out).unwrap();

        let vec_col = parsed["tables"]["audit_log"]["columns"]
            .as_array()
            .unwrap()
            .iter()
            .find(|c| c["name"] == "changed_fields")
            .unwrap();
        assert_eq!(vec_col["pg_type"], "JSONB");
        assert_eq!(vec_col["pg_bind"], "to_sql_jsonb");
        assert_eq!(vec_col["api_json"], "array");
    }

    #[test]
    fn missing_table_fails() {
        let manifest = LumiereSchemaManifest {
            version: 1,
            tables: vec![],
            enum_types: vec![],
        };
        let candidates = candidates_json();
        assert!(emit_codec_manifest(&candidates, &manifest).is_err());
    }
}
