//! Emit `query-registry.ts` from `crates/stdb-auth/assets/resource_registry.json`.

use anyhow::{Context, Result};
use serde_json::Value;

fn ts_string_array(values: &[String]) -> String {
    let parts: Vec<String> = values
        .iter()
        .map(|v| serde_json::to_string(v).expect("string json"))
        .collect();
    format!("[{}]", parts.join(", "))
}

fn emit_resource_entry(key: &str, entry: &Value) -> Result<String> {
    let table = entry
        .get("table")
        .and_then(|v| v.as_str())
        .context(format!("{key}: missing table"))?;
    let aliases = entry
        .get("aliases")
        .and_then(|v| v.as_array())
        .context(format!("{key}: missing aliases"))?;
    let default_restricted = entry
        .get("default_restricted")
        .and_then(|v| v.as_array())
        .context(format!("{key}: missing default_restricted"))?;
    let mandatory = entry
        .get("mandatory")
        .and_then(|v| v.as_array())
        .context(format!("{key}: missing mandatory"))?;

    let aliases_str: Vec<String> = aliases
        .iter()
        .filter_map(|v| v.as_str().map(String::from))
        .collect();
    let default_restricted_str: Vec<String> = default_restricted
        .iter()
        .filter_map(|v| v.as_str().map(String::from))
        .collect();
    let mandatory_str: Vec<String> = mandatory
        .iter()
        .filter_map(|v| v.as_str().map(String::from))
        .collect();

    Ok(format!(
        "  {key_lit}: {{\n    table: {table},\n    aliases: {aliases},\n    defaultRestricted: {default_restricted},\n    mandatory: {mandatory},\n  }}",
        key_lit = serde_json::to_string(key).expect("key json"),
        table = serde_json::to_string(table).expect("table json"),
        aliases = ts_string_array(&aliases_str),
        default_restricted = ts_string_array(&default_restricted_str),
        mandatory = ts_string_array(&mandatory_str),
    ))
}

pub fn emit_query_registry_typescript(registry_json: &str) -> Result<String> {
    let root: Value =
        serde_json::from_str(registry_json).context("parse resource_registry.json")?;
    let obj = root
        .as_object()
        .context("resource_registry.json root must be an object")?;

    let mut keys: Vec<&String> = obj.keys().collect();
    keys.sort();

    let union_parts: Vec<String> = keys
        .iter()
        .map(|k| serde_json::to_string(k).expect("key json"))
        .collect();

    let mut registry_entries = Vec::new();
    for key in &keys {
        registry_entries.push(emit_resource_entry(key, &obj[*key])?);
    }

    let keys_array = ts_string_array(
        &keys.iter().map(|s| (*s).clone()).collect::<Vec<_>>(),
    );

    Ok(format!(
        r#"// Auto-generated by `cargo run -p lumiere-codegen`. Do not edit.
// Source: crates/stdb-auth/assets/resource_registry.json (Rust-owned registry).

export interface ResourceEntry {{
  table: string
  aliases: string[]
  defaultRestricted: string[]
  mandatory: string[]
}}

export type QueryResourceKey =
{union}

export const RESOURCE_REGISTRY: Record<QueryResourceKey, ResourceEntry> = {{
{registry}
}}

export const QUERY_RESOURCE_KEYS: readonly QueryResourceKey[] = {keys_array}
"#,
        union = union_parts
            .iter()
            .map(|k| format!("  | {k}"))
            .collect::<Vec<_>>()
            .join("\n"),
        registry = registry_entries.join(",\n"),
        keys_array = keys_array,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_sorted_keys() {
        let json = r#"{"b":{"table":"b","aliases":[],"default_restricted":[],"mandatory":["id"]},"a":{"table":"a","aliases":[],"default_restricted":[],"mandatory":["id"]}}"#;
        let out = emit_query_registry_typescript(json).unwrap();
        assert!(out.contains("| \"a\""));
        assert!(out.find("| \"a\"").unwrap() < out.find("| \"b\"").unwrap());
    }
}
