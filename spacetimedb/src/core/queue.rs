#[spacetimedb::reducer]
pub fn enqueue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    params: EnqueueJobParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "create")?;
    enqueue_job_internal(ctx, organization_id, params)?;
    Ok(())
}

/// Claim a due pending job, or reclaim an expired lease.
#[spacetimedb::reducer]
pub fn claim_queue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: ClaimQueueJobParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "write")?;
    validate_nonempty(&params.lease_token, "lease_token")?;
    let mut job = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .ok_or("queue job not found")?;
    require_job_scope(&job, organization_id)?;
    require_revision(&job, params.expected_revision)?;
    require_worker(ctx, &job, params.worker_id)?;

    let lease_expires_at =
        timestamp_from_micros(params.lease_expires_at_micros, "lease_expires_at_micros")?;
    if lease_expires_at <= ctx.timestamp {
        return Err("lease_expires_at must be in the future".to_string());
    }
    let reclaiming = job.status == QueueJobStatus::Leased
        && job
            .lease_expires_at
            .map(|expires_at| expires_at <= ctx.timestamp)
            .unwrap_or(false);
    if job.status != QueueJobStatus::Pending && !reclaiming {
        return Err("queue job is not pending or reclaimable".to_string());
    }
    if job.status == QueueJobStatus::Pending && job.available_at > ctx.timestamp {
        return Err("queue job is not available yet".to_string());
    }

    if reclaiming {
        let expired_worker_id = job.lease_worker_id.ok_or("expired lease has no worker")?;
        let expired_token = job
            .lease_token
            .clone()
            .ok_or("expired lease has no token")?;
        record_attempt(
            ctx,
            &job,
            expired_worker_id,
            &expired_token,
            QueueAttemptOutcome::LeaseExpired,
            job.lease_expires_at,
            None,
            Some("lease expired before completion".to_string()),
        );
        if job.attempt_count >= job.max_attempts {
            ctx.db.queue_job().id().update(QueueJob {
                status: QueueJobStatus::DeadLettered,
                revision: job.revision + 1,
                lease_worker_id: None,
                lease_token: None,
                lease_expires_at: None,
                completed_at: Some(ctx.timestamp),
                last_error_summary: Some("lease expired before completion".to_string()),
                dead_lettered_at: Some(ctx.timestamp),
                dead_lettered_by: Some(ctx.sender()),
                dead_letter_reason: Some(
                    "maximum attempts exhausted after lease expiry".to_string(),
                ),
                ..job
            });
            return Ok(());
        }
    }

    job.attempt_count = job
        .attempt_count
        .checked_add(1)
        .ok_or("queue attempt count overflow")?;
    job.status = QueueJobStatus::Leased;
    job.lease_worker_id = Some(params.worker_id);
    job.lease_token = Some(params.lease_token.clone());
    job.lease_expires_at = Some(lease_expires_at);
    job.revision += 1;
    record_attempt(
        ctx,
        &job,
        params.worker_id,
        &params.lease_token,
        QueueAttemptOutcome::Leased,
        Some(lease_expires_at),
        None,
        None,
    );
    ctx.db.queue_job().id().update(job);
    Ok(())
}

#[spacetimedb::reducer]
pub fn renew_queue_job_lease(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: RenewQueueLeaseParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "write")?;
    let job = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .ok_or("queue job not found")?;
    require_job_scope(&job, organization_id)?;
    require_revision(&job, params.expected_revision)?;
    require_worker(ctx, &job, params.worker_id)?;
    require_active_lease(ctx, &job, params.worker_id, &params.lease_token)?;
    let lease_expires_at =
        timestamp_from_micros(params.lease_expires_at_micros, "lease_expires_at_micros")?;
    if lease_expires_at <= ctx.timestamp
        || job
            .lease_expires_at
            .map(|current| lease_expires_at <= current)
            .unwrap_or(true)
    {
        return Err("renewed lease expiry must extend the active lease".to_string());
    }
    record_attempt(
        ctx,
        &job,
        params.worker_id,
        &params.lease_token,
        QueueAttemptOutcome::LeaseRenewed,
        Some(lease_expires_at),
        None,
        None,
    );
    ctx.db.queue_job().id().update(QueueJob {
        lease_expires_at: Some(lease_expires_at),
        revision: job.revision + 1,
        ..job
    });
    Ok(())
}

#[spacetimedb::reducer]
pub fn complete_queue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: CompleteQueueJobParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "write")?;
    let job = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .ok_or("queue job not found")?;
    require_job_scope(&job, organization_id)?;

    if job.status == QueueJobStatus::Completed {
        let scope_key = receipt_scope_key(job.organization_id, job.company_id, &job.semantic_key);
        if ctx
            .db
            .queue_effect_receipt()
            .scope_key()
            .find(&scope_key)
            .map(|receipt| {
                receipt.worker_id == params.worker_id
                    && receipt.lease_token == params.lease_token
                    && params.outcome == QueueCompletionOutcome::Succeeded
            })
            .unwrap_or(false)
        {
            return Ok(());
        }
    }

    require_revision(&job, params.expected_revision)?;
    require_worker(ctx, &job, params.worker_id)?;
    require_active_lease(ctx, &job, params.worker_id, &params.lease_token)?;

    match params.outcome {
        QueueCompletionOutcome::Succeeded => {
            if params.error_summary.is_some() || params.retry_jitter_micros != 0 {
                return Err("successful completion cannot include failure fields".to_string());
            }
            let response_fingerprint = params
                .response_fingerprint
                .filter(|value| !value.trim().is_empty())
                .ok_or("successful completion requires response_fingerprint")?;
            let scope_key =
                receipt_scope_key(job.organization_id, job.company_id, &job.semantic_key);
            if let Some(receipt) = ctx.db.queue_effect_receipt().scope_key().find(&scope_key) {
                if receipt.input_hash != job.input_hash
                    || receipt.response_fingerprint != response_fingerprint
                {
                    return Err("effect receipt conflicts with prior semantic result".to_string());
                }
            } else {
                ctx.db.queue_effect_receipt().insert(QueueEffectReceipt {
                    scope_key,
                    organization_id: job.organization_id,
                    company_id: job.company_id,
                    job_id: job.id,
                    semantic_key: job.semantic_key.clone(),
                    input_hash: job.input_hash.clone(),
                    worker_id: params.worker_id,
                    lease_token: params.lease_token.clone(),
                    response_fingerprint,
                    correlation_id: job.correlation_id.clone(),
                    causation_id: job.causation_id.clone(),
                    completed_at: ctx.timestamp,
                });
            }
            record_attempt(
                ctx,
                &job,
                params.worker_id,
                &params.lease_token,
                QueueAttemptOutcome::Succeeded,
                job.lease_expires_at,
                None,
                None,
            );
            ctx.db.queue_job().id().update(QueueJob {
                status: QueueJobStatus::Completed,
                revision: job.revision + 1,
                lease_worker_id: None,
                lease_token: None,
                lease_expires_at: None,
                completed_at: Some(ctx.timestamp),
                last_error_summary: None,
                ..job
            });
        }
        QueueCompletionOutcome::Failed => {
            if params.response_fingerprint.is_some() {
                return Err("failed completion cannot include response_fingerprint".to_string());
            }
            let error_summary = params
                .error_summary
                .filter(|value| !value.trim().is_empty())
                .ok_or("failed completion requires error_summary")?;
            if job.attempt_count >= job.max_attempts {
                record_attempt(
                    ctx,
                    &job,
                    params.worker_id,
                    &params.lease_token,
                    QueueAttemptOutcome::DeadLettered,
                    job.lease_expires_at,
                    None,
                    Some(error_summary.clone()),
                );
                ctx.db.queue_job().id().update(QueueJob {
                    status: QueueJobStatus::DeadLettered,
                    revision: job.revision + 1,
                    lease_worker_id: None,
                    lease_token: None,
                    lease_expires_at: None,
                    completed_at: Some(ctx.timestamp),
                    last_error_summary: Some(error_summary.clone()),
                    dead_lettered_at: Some(ctx.timestamp),
                    dead_lettered_by: Some(ctx.sender()),
                    dead_letter_reason: Some(error_summary),
                    ..job
                });
            } else {
                let available_at = retry_available_at(
                    ctx.timestamp,
                    job.attempt_count,
                    params.retry_jitter_micros,
                )?;
                record_attempt(
                    ctx,
                    &job,
                    params.worker_id,
                    &params.lease_token,
                    QueueAttemptOutcome::RetryScheduled,
                    job.lease_expires_at,
                    Some(available_at),
                    Some(error_summary.clone()),
                );
                ctx.db.queue_job().id().update(QueueJob {
                    status: QueueJobStatus::Pending,
                    available_at,
                    revision: job.revision + 1,
                    lease_worker_id: None,
                    lease_token: None,
                    lease_expires_at: None,
                    last_error_summary: Some(error_summary),
                    ..job
                });
            }
        }
    }
    Ok(())
}

#[spacetimedb::reducer]
pub fn retry_dead_letter_queue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: RetryDeadLetterJobParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "write")?;
    validate_nonempty(&params.reason, "reason")?;
    if params.additional_attempts == 0 {
        return Err("additional_attempts must be greater than zero".to_string());
    }
    let job = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .ok_or("queue job not found")?;
    require_job_scope(&job, organization_id)?;
    require_revision(&job, params.expected_revision)?;
    if job.status != QueueJobStatus::DeadLettered {
        return Err("only a dead-lettered queue job can be retried".to_string());
    }
    let available_at = params
        .available_at_micros
        .map(|value| timestamp_from_micros(value, "available_at_micros"))
        .transpose()?
        .unwrap_or(ctx.timestamp);
    let max_attempts = job
        .max_attempts
        .checked_add(params.additional_attempts)
        .ok_or("max_attempts overflow")?;
    ctx.db.queue_job().id().update(QueueJob {
        status: QueueJobStatus::Pending,
        available_at,
        max_attempts,
        revision: job.revision + 1,
        completed_at: None,
        last_retried_at: Some(ctx.timestamp),
        last_retried_by: Some(ctx.sender()),
        last_retry_reason: Some(params.reason),
        ..job
    });
    audit_queue_job(ctx, organization_id, job_id, "retry", "manual_retry");
    Ok(())
}

fn audit_queue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    action: &'static str,
    changed_field: &'static str,
) {
    let company_id = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .and_then(|job| job.company_id);
    write_audit_log_v2(
        ctx,
        organization_id,
        AuditLogParams {
            company_id,
            table_name: "queue_job",
            record_id: job_id,
            action,
            old_values: None,
            new_values: None,
            changed_fields: vec![changed_field.to_string()],
            metadata: None,
        },
    );
}

#[spacetimedb::reducer]
pub fn cancel_queue_job(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: CancelQueueJobParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_job", "write")?;
    cancel_queue_job_internal(ctx, organization_id, job_id, params)
}

pub(crate) fn cancel_queue_job_internal(
    ctx: &ReducerContext,
    organization_id: u64,
    job_id: u64,
    params: CancelQueueJobParams,
) -> Result<(), String> {
    validate_nonempty(&params.reason, "reason")?;
    let job = ctx
        .db
        .queue_job()
        .id()
        .find(&job_id)
        .ok_or("queue job not found")?;
    require_job_scope(&job, organization_id)?;
    require_revision(&job, params.expected_revision)?;
    if matches!(
        job.status,
        QueueJobStatus::Completed | QueueJobStatus::Cancelled
    ) {
        return Err("completed or cancelled queue job cannot be cancelled".to_string());
    }
    if job.status == QueueJobStatus::Leased {
        record_attempt(
            ctx,
            &job,
            job.lease_worker_id.ok_or("active lease has no worker")?,
            job.lease_token
                .as_deref()
                .ok_or("active lease has no token")?,
            QueueAttemptOutcome::Cancelled,
            job.lease_expires_at,
            None,
            Some(params.reason.clone()),
        );
    }
    ctx.db.queue_job().id().update(QueueJob {
        status: QueueJobStatus::Cancelled,
        revision: job.revision + 1,
        lease_worker_id: None,
        lease_token: None,
        lease_expires_at: None,
        completed_at: Some(ctx.timestamp),
        cancelled_at: Some(ctx.timestamp),
        cancelled_by: Some(ctx.sender()),
        cancellation_reason: Some(params.reason),
        ..job
    });
    audit_queue_job(ctx, organization_id, job_id, "cancel", "manual_cancel");
    Ok(())
}

#[spacetimedb::reducer]
pub fn register_queue_worker(
    ctx: &ReducerContext,
    organization_id: u64,
    params: RegisterQueueWorkerParams,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_worker", "create")?;
    if let Some(company_id) = params.company_id {
        require_company_in_organization(ctx, organization_id, company_id)?;
    }
    validate_nonempty(&params.name, "name")?;
    if params.queues.is_empty() || params.queues.iter().any(|queue| queue.trim().is_empty()) {
        return Err("worker must register at least one non-empty queue".to_string());
    }
    ctx.db.queue_worker().insert(QueueWorker {
        id: 0,
        organization_id,
        company_id: params.company_id,
        name: params.name,
        queues: params.queues,
        is_active: true,
        last_heartbeat: ctx.timestamp,
        started_at: ctx.timestamp,
        metadata: params.metadata,
    });
    Ok(())
}

#[spacetimedb::reducer]
pub fn worker_heartbeat(
    ctx: &ReducerContext,
    organization_id: u64,
    worker_id: u64,
) -> Result<(), String> {
    check_permission(ctx, organization_id, "queue_worker", "write")?;
    let worker = ctx
        .db
        .queue_worker()
        .id()
        .find(&worker_id)
        .ok_or("queue worker not found")?;
    if worker.organization_id != organization_id {
        return Err("queue worker does not belong to this organization".to_string());
    }
    ctx.db.queue_worker().id().update(QueueWorker {
        last_heartbeat: ctx.timestamp,
        ..worker
    });
    Ok(())
}
