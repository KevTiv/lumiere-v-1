fn timestamp_from_micros(value: u64, field: &str) -> Result<Timestamp, String> {
    let micros = i64::try_from(value).map_err(|_| format!("{field} is out of range"))?;
    Ok(Timestamp::from_micros_since_unix_epoch(micros))
}

fn validate_nonempty(value: &str, field: &str) -> Result<(), String> {
    if value.trim().is_empty() {
        Err(format!("{field} must not be empty"))
    } else {
        Ok(())
    }
}

fn canonicalize_json(payload: &str) -> Result<String, String> {
    let value: serde_json::Value = serde_json::from_str(payload)
        .map_err(|error| format!("payload must be valid JSON: {error}"))?;
    serde_json::to_string(&value)
        .map_err(|error| format!("failed to canonicalize payload: {error}"))
}

/// Stable FNV-1a digest of canonical JSON. This is an equality fingerprint,
/// not a security primitive.
fn canonical_input_hash(canonical_payload: &str) -> String {
    let mut hash = 14_695_981_039_346_656_037_u64;
    for byte in canonical_payload.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(1_099_511_628_211);
    }
    format!("fnv1a64:{hash:016x}")
}

/// Build the same canonical input fingerprint used by the enqueue path. Domain
/// callers may include it in a semantic key when each distinct input revision
/// is independently meaningful.
pub(crate) fn queue_payload_hash(payload: &str) -> Result<String, String> {
    Ok(canonical_input_hash(&canonicalize_json(payload)?))
}

fn receipt_scope_key(organization_id: u64, company_id: Option<u64>, semantic_key: &str) -> String {
    let company = company_id
        .map(|value| value.to_string())
        .unwrap_or_else(|| "_".to_string());
    format!("{organization_id}:{company}:{semantic_key}")
}

fn record_attempt(
    ctx: &ReducerContext,
    job: &QueueJob,
    worker_id: u64,
    lease_token: &str,
    outcome: QueueAttemptOutcome,
    lease_expires_at: Option<Timestamp>,
    available_at: Option<Timestamp>,
    error_summary: Option<String>,
) {
    ctx.db.queue_attempt().insert(QueueAttempt {
        id: 0,
        organization_id: job.organization_id,
        company_id: job.company_id,
        job_id: job.id,
        attempt_number: job.attempt_count,
        worker_id,
        lease_token: lease_token.to_string(),
        outcome,
        lease_expires_at,
        available_at,
        error_summary,
        recorded_by: ctx.sender(),
        recorded_at: ctx.timestamp,
    });
}

fn require_job_scope(job: &QueueJob, organization_id: u64) -> Result<(), String> {
    if job.organization_id != organization_id {
        Err("job does not belong to this organization".to_string())
    } else {
        Ok(())
    }
}

fn require_revision(job: &QueueJob, expected_revision: u64) -> Result<(), String> {
    if job.revision != expected_revision {
        Err(format!(
            "stale queue job revision: expected {}, current {}",
            expected_revision, job.revision
        ))
    } else {
        Ok(())
    }
}

fn require_worker(
    ctx: &ReducerContext,
    job: &QueueJob,
    worker_id: u64,
) -> Result<QueueWorker, String> {
    let worker = ctx
        .db
        .queue_worker()
        .id()
        .find(&worker_id)
        .ok_or("queue worker not found")?;
    if !worker.is_active {
        return Err("queue worker is inactive".to_string());
    }
    if worker.organization_id != job.organization_id {
        return Err("queue worker does not belong to the job organization".to_string());
    }
    if worker.company_id.is_some() && worker.company_id != job.company_id {
        return Err("queue worker does not belong to the job company".to_string());
    }
    if !worker.queues.iter().any(|queue| queue == &job.queue_name) {
        return Err("queue worker is not registered for this queue".to_string());
    }
    Ok(worker)
}

fn require_active_lease(
    ctx: &ReducerContext,
    job: &QueueJob,
    worker_id: u64,
    lease_token: &str,
) -> Result<(), String> {
    if job.status != QueueJobStatus::Leased {
        return Err("queue job is not leased".to_string());
    }
    if job.lease_worker_id != Some(worker_id) || job.lease_token.as_deref() != Some(lease_token) {
        return Err("queue lease owner or token does not match".to_string());
    }
    if job
        .lease_expires_at
        .map(|expires_at| expires_at <= ctx.timestamp)
        .unwrap_or(true)
    {
        return Err("queue lease has expired".to_string());
    }
    Ok(())
}

fn retry_available_at(
    now: Timestamp,
    attempt_count: u32,
    jitter_micros: u64,
) -> Result<Timestamp, String> {
    if jitter_micros > MAX_JITTER_MICROS {
        return Err(format!(
            "retry_jitter_micros must not exceed {MAX_JITTER_MICROS}"
        ));
    }
    let exponent = attempt_count.saturating_sub(1).min(31);
    let backoff_secs = BASE_BACKOFF_SECS
        .saturating_mul(1_u64 << exponent)
        .min(MAX_BACKOFF_SECS);
    let backoff_micros = backoff_secs.saturating_mul(1_000_000);
    let total_micros = backoff_micros
        .saturating_add(jitter_micros)
        .min(MAX_BACKOFF_SECS.saturating_mul(1_000_000));
    Ok(now + Duration::from_micros(total_micros))
}

/// The only insertion path for `QueueJob`, including domain-internal callers.
/// Identical semantic replays return the existing job; input changes fail.
pub(crate) fn enqueue_job_internal(
    ctx: &ReducerContext,
    organization_id: u64,
    params: EnqueueJobParams,
) -> Result<QueueJob, String> {
    if let Some(company_id) = params.company_id {
        require_company_in_organization(ctx, organization_id, company_id)?;
    }
    validate_nonempty(&params.queue_name, "queue_name")?;
    validate_nonempty(&params.job_type, "job_type")?;
    validate_nonempty(&params.semantic_key, "semantic_key")?;
    validate_nonempty(&params.correlation_id, "correlation_id")?;
    if params.max_attempts == 0 {
        return Err("max_attempts must be greater than zero".to_string());
    }

    let payload = canonicalize_json(&params.payload)?;
    let input_hash = canonical_input_hash(&payload);
    if let Some(existing) = ctx.db.queue_job().iter().find(|job| {
        job.organization_id == organization_id
            && job.company_id == params.company_id
            && job.semantic_key == params.semantic_key
    }) {
        if existing.input_hash == input_hash {
            return Ok(existing);
        }
        return Err("semantic key was already used with different input".to_string());
    }

    let available_at = params
        .available_at_micros
        .map(|value| timestamp_from_micros(value, "available_at_micros"))
        .transpose()?
        .unwrap_or(ctx.timestamp);
    Ok(ctx.db.queue_job().insert(QueueJob {
        id: 0,
        organization_id,
        company_id: params.company_id,
        queue_name: params.queue_name,
        job_type: params.job_type,
        payload,
        semantic_key: params.semantic_key,
        input_hash,
        priority: params.priority,
        attempt_count: 0,
        max_attempts: params.max_attempts,
        status: QueueJobStatus::Pending,
        available_at,
        lease_worker_id: None,
        lease_token: None,
        lease_expires_at: None,
        revision: 0,
        correlation_id: params.correlation_id,
        causation_id: params.causation_id,
        completed_at: None,
        last_error_summary: None,
        dead_lettered_at: None,
        dead_lettered_by: None,
        dead_letter_reason: None,
        last_retried_at: None,
        last_retried_by: None,
        last_retry_reason: None,
        cancelled_at: None,
        cancelled_by: None,
        cancellation_reason: None,
        created_by: ctx.sender(),
        created_at: ctx.timestamp,
        metadata: params.metadata,
    }))
}

