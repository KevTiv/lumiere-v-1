//! Durable, leased background-work queue.
//!
//! Delivery is at least once. Semantic enqueue keys and immutable effect
//! receipts let consumers make the resulting business effect idempotent.
use std::time::Duration;

use spacetimedb::{Identity, ReducerContext, SpacetimeType, Table, Timestamp};

use crate::core::organization::require_company_in_organization;
use crate::helpers::{check_permission, write_audit_log_v2, AuditLogParams};
use crate::types::{QueueAttemptOutcome, QueueCompletionOutcome, QueueJobStatus};

const BASE_BACKOFF_SECS: u64 = 1;
const MAX_BACKOFF_SECS: u64 = 60 * 60;
const MAX_JITTER_MICROS: u64 = 60 * 1_000_000;

